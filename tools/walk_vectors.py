"""Test vectors for the port's walk (src/world/actor_walk.h), taken from the original in the
emulation oracle.

usage: .venv/bin/python -I tools/walk_vectors.py > tests/unit/walk_vectors.inc

Three small attribute maps: an open field, the walls of tools/path_vectors.py, and hills
whose corners' heights follow a formula (Height below, and in tests/unit/walk_test.cpp).
Each has a script of searches and walks as tools/walk_oracle.py makes them, with short
walks, then chosen walks that each hang on one value; every walk's result is the original's
CGameActor::ProcessState.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle
import path_vectors
import walk_oracle

HILLS = [
    "............",
    "....##......",
    "............",
    "......o.....",
    "............",
    "..#.........",
    "............",
    "............",
]


# Walks whose results hang on one value, each from (1, 1) on the open field, along a path that
# ends at 1450: a turn of exactly 22.5°, timeGetTime just at the fade's end, and the
# server's time just at the path's end.
START = "0xc1b40000 0xc18c0000"
DECIDING = {
    "open": [
        "F 1000 1 1 8 8 4 1 150",
        f"W {START} 0x43a8c000 0x0 0x40800000 0x0 0 0 0 0 8 0 0 4294967295 0 1000 1072 1000 1072",
        f"W {START} 0x0 0x0 0x40800000 0x0 0 0 0 0 8 0 1072 4294967295 0 1000 1072 1000 1072",
        f"W {START} 0x0 0x0 0x40800000 0x0 0 0 0 0 8 0 0 4294967295 0 1000 1072 1450 1522",
    ],
}


def height(x, y, corner):
    return float((x * 7 + y * 13 + corner * 5) % 11 - 5)


def gat(rows, hilly):
    width, height_ = len(rows[0]), len(rows)
    data = bytearray(b"GRAT\x01\x02" + struct.pack("<ii", width, height_))
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            h = [height(x, y, k) if hilly else 0.0 for k in range(4)]
            data += struct.pack("<4fi", *h, path_vectors.ATTRIBUTES[c])
    return bytes(data)


def main():
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", HILLS, True)]
    oracle = path_oracle.Oracle()
    lines = ["// Generated by tools/walk_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps, a row at a time from y = 0: '.' attribute 0, '#' 1, 'o' 5, '3' 3, '6' 6; hilly")
    lines.append("// maps' corner heights from the formula in walk_test.cpp, the others' 0.")
    lines.append("static const WalkMapVector kWalkMaps[] = {")
    for name, rows, hilly in maps:
        lines.append(f"    {{\"{name}\", {len(rows[0])}, {len(rows)}, {str(hilly).lower()}, \"{''.join(rows)}\"}},")
    lines.append("};")
    lines.append("// Each map's searches and walks in order, on one finder and one path (tools/walk_oracle.py's")
    lines.append("// script and output).")
    lines.append("static const WalkQueryVector kWalkQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height_ = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_walks(name, width, height_, attrs, 24, updates=(4, 12, 30, 80))
        script += DECIDING.get(name, [])
        for query, result in zip(script, oracle.run(gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
