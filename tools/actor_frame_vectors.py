"""Test vectors for an actor's direction and frame (world::GameActorDirection and
world::UpdateGameActorFrame, docs/world/walk.md#the-direction), taken from the original in the
emulation oracle.

usage: .venv/bin/python -I tools/actor_frame_vectors.py > tests/unit/actor_frame_vectors.inc

  - CGameActor::GetDirection (00502b00) with the camera's yaw at CGameMode+0xb8 (the CView)
    +0x20: assorted jobs (players, the portal, NPCs, 1000, monsters, the mounted 7 and 14),
    +0x21c, base actions, yaws and facings, with turns just on and either side of 22.5 and
    337.5; then a player standing at every edge between two directions, a step or two either
    side.
  - CRenderObject::UpdateFrame (00500830) on a CGameActor (its vtable 005e95c0), so through
    GetDirection: the same, with assorted delays, repeats, play modes, times, frames and frame
    counts (GetFrameCount answered here), the action, frame and finished after.
The x87 runs at single precision, as in the client.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn.x86_const import UC_X86_REG_FPCW  # noqa: E402

from emu import Emulator  # noqa: E402
from emu.winapi import Stub  # noqa: E402

GET_DIRECTION, UPDATE_FRAME, GET_FRAME_COUNT, GET_GAME_MODE = 0x502B00, 0x500830, 0x421A80, 0x4CBF30
GAME_ACTOR_VTABLE, CVIEW_SIZE = 0x5E95C0, 0x1C0
JOBS = [0, 1, 7, 7, 14, 14, 23, 44, 45, 46, 120, 999, 1000, 1001, 1002, 1300, -1]


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def near(x, steps):
    """x moved by a number of float steps up, through zero to the smallest denormals. (A NaN
    facing would hang GetDirection's loop, as it hangs the original's.)"""
    b = bits(f32(x)) & 0x7FFFFFFF
    i = b if x > 0 else -b
    i += steps
    return struct.unpack("<f", struct.pack("<I", i if i >= 0 else (-i | 0x80000000)))[0]


def facings(rng, yaw):
    """Facings whose turn from the yaw lands on and beside the rounding edges, and others."""
    out = []
    for edge in (22.5, 337.5, 0.0, 45.0, 67.5, 180.0):
        for steps in (-1, 0, 1):
            out.append(f32(near(-edge - yaw, steps)))
    out += [f32(rng.uniform(-720, 720)) for _ in range(6)]
    return out


def main():
    rng = random.Random(1907)
    emu = Emulator().init_crt()
    emu.uc.reg_write(UC_X86_REG_FPCW, 0x007F)
    view = emu.scratch(size=CVIEW_SIZE)
    mode = emu.scratch(size=0x400)
    emu.write_u32(mode + 0xB8, view)
    emu.replace_thiscall(GET_GAME_MODE, 0, lambda this: mode)
    clock = [0]
    emu.api.stubs["WINMM.DLL!timeGetTime"] = Stub(0, lambda: clock[0])
    count = [1]
    emu.replace_thiscall(GET_FRAME_COUNT, 1, lambda this, action: count[0])
    actor = emu.scratch(size=0x300)
    act = emu.scratch(size=0x144)

    def reset(job, effect, base):
        emu.mem_write(actor, bytes(0x300))
        emu.write_u32(actor, GAME_ACTOR_VTABLE)
        emu.write_u32(actor + 0x1B8, job & 0xFFFFFFFF)
        emu.write_u32(actor + 0x21C, effect)
        emu.write_u32(actor + 0x20, base)
        emu.write_u32(actor + 0x9C, act)

    lines = ["// Generated by tools/actor_frame_vectors.py from the original in the emulation oracle."]
    lines.append("// CGameActor::GetDirection (00502b00): {job, +0x21c, base action, facing, camera yaw,")
    lines.append("// direction}.")
    lines.append("static const ActorDirectionVector kActorDirections[] = {")
    for _ in range(24):
        yaw = f32(rng.choice([0.0, 0.0, 45.0, 90.0, 300.0, rng.uniform(0, 360)]))
        emu.mem_write(view + 0x20, struct.pack("<f", yaw))
        for facing in facings(rng, yaw):
            job = rng.choice(JOBS)
            effect = rng.choice([0, 0x20, rng.getrandbits(32)])
            base = rng.choice([0, 0, 8, 16, 24, 32, 80])
            reset(job, effect, base)
            d = emu.call(GET_DIRECTION, bits(facing), this=actor).eax
            lines.append(f"    {{{job}, 0x{effect:08x}, {base}, 0x{bits(facing):08x}, 0x{bits(yaw):08x}, {d}}},")
    # Rounded directions at each edge between two, a step either side: the product with the
    # double 1/45 truncates below the edge where the float 1/45's would not.
    emu.mem_write(view + 0x20, struct.pack("<f", 0.0))
    for edge in (22.5 + 45.0 * k for k in range(8)):
        for steps in (-2, -1, 0, 1, 2):
            facing = f32(near(-edge, steps))
            reset(0, 0, 0)
            d = emu.call(GET_DIRECTION, bits(facing), this=actor).eax
            lines.append(f"    {{0, 0x00000000, 0, 0x{bits(facing):08x}, 0x00000000, {d}}},")
    lines.append("};")
    lines.append("// CRenderObject::UpdateFrame (00500830) on a CGameActor: {job, +0x21c, base action, facing,")
    lines.append("// camera yaw, delay, repeats, play mode, start, now, finished, held, frame before, frame")
    lines.append("// count}, then the action, the frame and finished after.")
    lines.append("static const ActorFrameVector kActorFrames[] = {")
    for _ in range(300):
        job = rng.choice(JOBS)
        effect = rng.choice([0, 0x20])
        base = rng.choice([0, 0, 8, 16, 24, 32])
        yaw = f32(rng.choice([0.0, 45.0, 135.0, rng.uniform(0, 360)]))
        facing = f32(rng.choice([-22.5 - yaw, -337.5 - yaw, rng.uniform(0, 360), 200.0]))
        delay = f32(rng.choice([1.0, 2.0, 4.0, 6.5, 0.75, 12.0]))
        repeats = f32(rng.choice([1.0, 1.0, 2.0, 3.5]))
        play = rng.choice([0, 0, 0, 1, 1, 2])
        start = rng.randrange(0, 1 << 31)
        now = (start + rng.choice([0, 1, 23, 24, 100, 950, 4000, 20000, rng.randrange(1 << 20)])) & 0xFFFFFFFF
        finished, held = int(rng.random() < 0.1), int(rng.random() < 0.1)
        frame = rng.randrange(0, 12)
        count[0] = rng.choice([1, 2, 3, 4, 5, 8, 13])
        reset(job, effect, base)
        emu.mem_write(view + 0x20, struct.pack("<f", yaw))
        emu.mem_write(actor + 0x38, struct.pack("<f", facing))
        emu.mem_write(actor + 0x44, struct.pack("<f", delay))
        emu.mem_write(actor + 0x4C, struct.pack("<f", repeats))
        emu.write_u32(actor + 0x54, play)
        emu.write_u32(actor + 0x70, start)
        emu.write_u32(actor + 0x28, frame)
        emu.mem_write(actor + 0x81, bytes([finished, held]))
        clock[0] = now
        emu.call(UPDATE_FRAME, this=actor)
        after = (emu.read_u32(actor + 0x24), emu.read_u32(actor + 0x28), emu.mem_read(actor + 0x81, 1)[0])
        lines.append(f"    {{{job}, 0x{effect:08x}, {base}, 0x{bits(facing):08x}, 0x{bits(yaw):08x}, "
                     f"0x{bits(delay):08x}, 0x{bits(repeats):08x}, {play}, 0x{start:08x}, 0x{now:08x}, {finished}, "
                     f"{held}, {frame}, {count[0]}, {after[0]}, {after[1]}, {after[2]}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
