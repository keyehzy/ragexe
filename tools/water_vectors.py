"""Test vectors for the port's water steps (docs/render/ground.md#the-water), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/water_vectors.py > tests/unit/water_vectors.inc

C3dGround::SetWaterParams (004bc410) runs with the arguments CWorld::LoadWorld
(004c3ab0) passes from a .rsw's water (two of them truncated), on a C3dGround15 that
C3dGround15::Reset left with frame and phase 0, then C3dGround15 004bc450 steps it 200
times. TextureCache::GetTexture (0040cc00) records the names. Recorded after each step:
the frame (+0x5c), the phase (+0x60) and the texture name.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402

SET_WATER_PARAMS, STEP_WATER, GET_TEXTURE = 0x4BC410, 0x4BC450, 0x40CC00
STEPS = 200

# .rsw water: level, type, wave height (+0x170), phase step (+0x174), step (+0x178),
# interval (+0x17c).
CASES = [
    (0.0, 0, 1.0, 2.0, 50.0, 3),
    (-12.5, 3, 2.5, 7.9, 30.0, 1),
    (4.0, 7, 0.5, 359.0, 12.25, 5),
    (1.0, 11, 1.0, -45.6, -20.0, 2),
    (0.0, 5, 3.0, 721.0, 90.0, 7),
    (2.0, -1, 1.5, 180.0, 0.0, 4),
]


def main():
    emu = Emulator().init_crt()
    names = []

    def get_texture(this, name, flag):
        names.append(emu.mem_read(name, 64).split(b"\0")[0])
        return 0x71000000 + len(names)

    emu.replace_thiscall(GET_TEXTURE, 2, get_texture)
    lines = ["// Generated by tools/water_vectors.py from the original in the emulation oracle."]
    cases = []
    for k, (level, kind, height, phase_step, step, interval) in enumerate(CASES):
        ground = emu.scratch(size=0x100)
        bits = lambda f: struct.unpack("<I", struct.pack("<f", f))[0]  # noqa: E731
        emu.call(SET_WATER_PARAMS, bits(level), kind & 0xFFFFFFFF, interval, int(step) & 0xFFFFFFFF,
                 int(phase_step) & 0xFFFFFFFF, bits(height), this=ground)
        names.clear()
        rows = []
        for _ in range(STEPS):
            emu.call(STEP_WATER, this=ground)
            frame, phase = struct.unpack("<ii", emu.mem_read(ground + 0x5C, 8))
            rows.append((frame, phase, names[-1]))
        fields = struct.unpack("<6I", emu.mem_read(ground + 0x40, 24))
        lines.append(f"static const WaterStep kWaterSteps{k}[] = {{")
        lines += [f'    {{{f}, {p}, "{"".join(f"\\x{b:02x}" for b in n)}"}},' for f, p, n in rows]
        lines.append("};")
        rsw = (bits(level), kind & 0xFFFFFFFF, bits(height), bits(phase_step), bits(step), interval)
        cases.append(f"    {{{{{', '.join(f'0x{v:08x}' for v in rsw)}}}, "
                     f"{{{', '.join(f'0x{v:08x}' for v in fields)}}}, kWaterSteps{k}}},")
    lines.append("// {.rsw water {level, type, wave height, phase step, step, interval}, the ground's")
    lines.append("// +0x40 to +0x54 after SetWaterParams {level, interval, step, phase step, type, wave")
    lines.append(f"// height}}, {STEPS} steps {{frame, phase, texture}}}}.")
    lines.append("static const WaterVector kWaterVectors[] = {")
    lines += cases
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
