"""Test vectors for the port's fog (docs/render/fog.md), taken from the original in the
emulation oracle.

usage: .venv/bin/python -I tools/fog_vectors.py > tests/unit/fog_vectors.inc

  - ParseHexDigits (004e4cc0) on colours as the table writes them, and on short, long,
    mixed-case and junk strings.
  - A synthetic fogParameterTable.txt read by ClientState::LoadFogParameterTable
    (00598e10) into g_ClientState, then CGameMode 00516570 for map names in it and not:
    whether it turns the fog on (SceneRenderer 00411010, recorded) and the fog globals
    00625ea4 to 00625eb4 it leaves, from sentinels.
  - RenderPrimitive::ComputeVertexFog (0040c2e0) on vertices at many depths, under
    assorted fog ranges: the specular colour it writes.
  - SceneRenderer::SetupProjection (00411090) with the fog on and off, with and without
    the device's vertex fog, in linear mode and not: the render states it sets, in order.
The x87 runs at single precision, as DirectDraw's FPUSETUP leaves it in the client.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn.x86_const import UC_X86_REG_FPCW  # noqa: E402

from emu import Emulator  # noqa: E402

PARSE_HEX, LOAD_FOG_TABLE, APPLY_MAP_FOG = 0x4E4CC0, 0x598E10, 0x516570
SET_FOG_ENABLED, VERTEX_FOG, SETUP_PROJECTION = 0x411010, 0x40C2E0, 0x411090
SHOW_ERROR_MESSAGE = 0x4CC110
G_CLIENT_STATE, G_SCENE_RENDERER = 0x686670, 0x625E98
FOG_MODE, FOG_COLOR, FOG_RANGE, FOG_DENSITY, FOG_START, FOG_END = (
    0x625EA0, 0x625EA4, 0x625EA8, 0x625EAC, 0x625EB0, 0x625EB4)
DEVICE_SOFTWARE, DEVICE_TRI_RASTER_CAPS = 0x623BBC, 0x623A5C  # g_C3dDevice +0x1ec, +0x48 +0x44
RASTERCAPS_FOGVERTEX = 0x80
SCENE_RENDERER_SIZE, GAME_MODE_SIZE = 0x2A0, 0x400
SENTINEL = 0xDEADBEEF

HEX_STRINGS = [
    b"0x2275A9FF", b"0x222A00FF", b"0x224a6976", b"0xffFFEFA3", b"0x3020ffff", b"0xffffffff",
    b"", b"0", b"0x", b"0x1", b"ab", b"abc", b"0X1F", b"ff", b"12345678", b"0x123456789",
    b"0x0123456789abcdef", b"0xGG12", b"0x12 34", b"#1f", b"0x\xff\x80a", b"0x-1", b"0xAaBbCcDd",
    b"0x" + b"f" * 40, b"0x7fffffff", b"0x80000000", b"0x00000000ff",
]

# A synthetic table: a name and four values a record (start, end, colour, density), the
# values in the forms atof and ParseHexDigits meet.
FOG_TABLE = (
    b"gef_fild12.rsw#\r\n0.2#\r\n0.45#\r\n0x2275A9FF#\r\n0.5#\r\n"
    b"beach_dun.rsw#\r\n0.15#\r\n0.8#\r\n0x222A00FF#\r\n0.5#\r\n"
    b"cmd_fild01.rsw#0.1#0.7#0x224a6976#0.4#\r\n"
    b"xmas.rsw#0.23#0.6#0xffffffff#0.3#\r\n"
    b"blank.rsw#  -0.25#+1.5e0#0x#.75#\r\n"
    b"junk.rsw#abc#1.0x#zz#-#\r\n"
    b"exponents.rsw#1e-3#2.5D1#0X10#1E40#\r\n"
    b"long.rsw#0.1000000000000000055511151231257827#0.333333333333333314829616256247390992939472198486328125#"
    b"0x0123456789#123456789012345678901234567890#\r\n"
    b"tiny.rsw#1e-50#-1e-50#0x1#7.006492321624085e-46#\r\n"
    b"same.rsw#0.5#0.5#0x10203040#0#\r\n"
    b"inverted.rsw#0.9#0.1#0xff000000#1#\r\n"
    b"PRONTERA.RSW#0.3#0.9#0x00ff00ff#0.25#\r\n"
    b"z.rsw#0.05#0.95#0xABCDEF#0.5#"
)
LOOKUPS = [
    b"gef_fild12.rsw", b"beach_dun.rsw", b"cmd_fild01.rsw", b"xmas.rsw", b"blank.rsw", b"junk.rsw",
    b"exponents.rsw", b"long.rsw", b"tiny.rsw", b"same.rsw", b"inverted.rsw", b"PRONTERA.RSW",
    b"z.rsw", b"prontera.rsw", b"gef_fild12", b"gef_fild12.rsw2", b"", b"a.rsw", b"zz.rsw",
]

# Fog ranges (start, end) for ComputeVertexFog, as fractions of near 10 to far 1500.
RANGES = [(0.2, 0.45), (0.15, 0.8), (0.0, 1.0), (0.5, 0.5), (0.9, 0.1), (-0.25, 1.5), (0.0, 0.0),
          (0.1, 0.7), (0.23, 0.6)]


def bits(f):
    return struct.unpack("<I", struct.pack("<f", f))[0]


def single_precision(emu):
    emu.uc.reg_write(UC_X86_REG_FPCW, 0x007F)


def rhw_values():
    rng = random.Random(11)
    out = [1.0, 0.1, 1 / 10, 1 / 1500, 1 / 1490, 1 / 160, 1 / 350, 1 / 700, 1 / 1000, 2.0, 0.0,
           -0.01, 1e-30, 3e38, 1 / 307, 1 / 308]
    for z in range(5, 1600, 7):
        out.append(1.0 / z)
    out += [1.0 / rng.uniform(5.0, 1600.0) for _ in range(150)]
    return [struct.unpack("<f", struct.pack("<f", r))[0] for r in out]


def c_bytes(data):
    return '"' + "".join(f"\\x{b:02x}" for b in data) + '"'


def main():
    lines = ["// Generated by tools/fog_vectors.py from the original in the emulation oracle."]

    emu = Emulator().init_crt()
    single_precision(emu)
    lines.append("// ParseHexDigits (004e4cc0): {text, length, value}.")
    lines.append("static const HexVector kHexVectors[] = {")
    for s in HEX_STRINGS:
        value = emu.call(PARSE_HEX, emu.cstr(s)).eax
        lines.append(f"    {{{c_bytes(s)}, {len(s)}, 0x{value:08x}}},")
    lines.append("};")

    emu.serve_data_files({"data\\fogparametertable.txt": FOG_TABLE})
    assert emu.call(LOAD_FOG_TABLE, this=G_CLIENT_STATE).eax == 1
    enabled = []
    emu.replace_thiscall(SET_FOG_ENABLED, 1, lambda this, on: enabled.append(on) or 0)
    emu.write_u32(G_SCENE_RENDERER, emu.scratch(size=SCENE_RENDERER_SIZE))
    mode = emu.scratch(size=GAME_MODE_SIZE)
    lines.append(f"static const char kFogTable[] = {c_bytes(FOG_TABLE)};")
    lines.append("// CGameMode 00516570 with the fog flag on, then off: {map name, the flag it passes")
    lines.append("// SetFogEnabled each time, and with the flag on the globals from sentinels: colour,")
    lines.append("// density, start, end}.")
    lines.append("static const MapFogVector kMapFogVectors[] = {")
    for name in LOOKUPS:
        emu.mem_write(mode + 0x50, name + b"\0")
        results = []
        for flag in (1, 0):
            for g in (FOG_COLOR, FOG_DENSITY, FOG_START, FOG_END):
                emu.write_u32(g, SENTINEL)
            enabled.clear()
            emu.call(APPLY_MAP_FOG, flag, this=mode)
            assert len(enabled) == 1
            results.append((enabled[0], [emu.read_u32(g) for g in (FOG_COLOR, FOG_DENSITY, FOG_START, FOG_END)]))
        assert results[1][1] == [SENTINEL] * 4
        on, values = results[0]
        lines.append(f"    {{{c_bytes(name)}, {on}, {results[1][0]}, "
                     f"{{{', '.join(f'0x{v:08x}' for v in values)}}}}},")
    lines.append("};")

    rhws = rhw_values()
    vertices = emu.scratch(size=0x20 * len(rhws))
    prim = emu.scratch(size=0x24)
    emu.write_u32(prim, vertices)
    emu.write_u32(prim + 8, len(rhws))
    lines.append("// ComputeVertexFog (0040c2e0): the vertices' rhw, then for each fog range {start,")
    lines.append("// end} the specular colour of each vertex.")
    lines.append("static const std::uint32_t kVertexFogRhw[] = {")
    lines += [f"    {', '.join(f'0x{bits(r):08x}' for r in rhws[i:i + 8])}," for i in range(0, len(rhws), 8)]
    lines.append("};")
    cases = []
    for k, (start, end) in enumerate(RANGES):
        emu.mem_write(vertices, b"".join(struct.pack("<4fII2f", 0, 0, 0, r, 0xFFFFFFFF, 0x12345678, 0, 0)
                                         for r in rhws))
        emu.write_u32(FOG_START, bits(start))
        emu.write_u32(FOG_END, bits(end))
        emu.call(VERTEX_FOG, this=prim)
        spec = [emu.read_u32(vertices + 0x20 * i + 0x14) for i in range(len(rhws))]
        lines.append(f"static const std::uint32_t kVertexFog{k}[] = {{")
        lines += [f"    {', '.join(f'0x{v:08x}' for v in spec[i:i + 8])}," for i in range(0, len(spec), 8)]
        lines.append("};")
        cases.append(f"    {{0x{bits(start):08x}, 0x{bits(end):08x}, kVertexFog{k}}},")
    lines.append("static const VertexFogVector kVertexFogVectors[] = {")
    lines += cases
    lines.append("};")

    lines.append("// SetupProjection (00411090): {fog on, the device's vertex fog, mode, range fog,")
    lines.append("// colour, density, start, end}, the render states it sets {state, value}, and how many")
    lines.append("// times it shows the missing fog message.")
    setups = []
    rng = random.Random(3)
    variants = [(on, vertex, m, rf) for on in (1, 0) for vertex in (1, 0) for m in (3, 1) for rf in (1, 0)]
    for k, (on, vertex, m, rf) in enumerate(variants):
        emu = Emulator().init_crt()
        single_precision(emu)
        errors = []
        # __cdecl, so a replacement that pops nothing; the text is the message's.
        emu.replace_thiscall(SHOW_ERROR_MESSAGE, 0, lambda this: errors.append(1) or 0)
        device = emu.directx.create_device()
        sr = emu.scratch(size=SCENE_RENDERER_SIZE)
        emu.write_u32(sr + 0x78, device.address)
        emu.write_u32(sr + 0x44, on)
        emu.write_u32(sr + 0x48, 1)
        emu.mem_write(sr + 0x10, struct.pack("<f", 0.75))
        emu.write_u32(DEVICE_SOFTWARE, 0)
        emu.write_u32(DEVICE_TRI_RASTER_CAPS, RASTERCAPS_FOGVERTEX if vertex else 0x7F)
        start, end = rng.choice(RANGES)
        color, density = rng.getrandbits(32), rng.choice([0.5, 0.3, 0.25, 1.0])
        state = [m, color, rf, bits(density), bits(start), bits(end)]
        for g, v in zip((FOG_MODE, FOG_COLOR, FOG_RANGE, FOG_DENSITY, FOG_START, FOG_END), state):
            emu.write_u32(g, v)
        first = len(emu.directx.calls)
        emu.call(SETUP_PROJECTION, this=sr)
        assert emu.read_u32(sr + 0x48) == 0
        rows = [(c.args[0], c.args[1]) for c in emu.directx.calls[first:] if c.method == "SetRenderState"]
        lines.append(f"static const std::uint32_t kSetupCalls{k}[] = {{")
        lines.append("    " + ", ".join(f"0x{s:x}, 0x{v:08x}" for s, v in rows) + ("," if rows else "0"))
        lines.append("};")
        setups.append(f"    {{{on}, {vertex}, {{{', '.join(f'0x{v:08x}' for v in state)}}}, "
                      f"kSetupCalls{k}, {len(rows)}, {len(errors)}}},")
    lines.append("static const SetupVector kSetupVectors[] = {")
    lines += setups
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
