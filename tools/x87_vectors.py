"""Test vectors for the port's x87 arithmetic (src/core/x87.h), taken from the x87 in the
emulation oracle.

usage: .venv/bin/python -I tools/x87_vectors.py > tests/unit/x87_vectors.inc

fadd, fsub, fmul and fdiv of two memory operands, and fsqrt of one, each loaded with fld and
stored with fstp: floats under single precision (control word 0x7f, as DirectDraw's
FPUSETUP leaves the client's main thread) and doubles under double precision (0x27f, the
CRT's default, which a new thread starts with). The operands are every pair of zeros,
ones, infinities, quiet NaNs of either sign with assorted payloads, signalling NaNs and
large values, and random pairs of numbers.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn import UC_PROT_ALL  # noqa: E402
from unicorn.x86_const import UC_X86_REG_FPCW  # noqa: E402

from emu import Emulator  # noqa: E402

CODE = 0x7F000000
# mov eax, [esp + out]; fld [esp + 4]; op [esp + b]; fstp [eax]; ret
FLOAT_OPS = {"add": b"\xd8\x44\x24\x08", "sub": b"\xd8\x64\x24\x08", "mul": b"\xd8\x4c\x24\x08",
             "div": b"\xd8\x74\x24\x08"}
DOUBLE_OPS = {"add": b"\xdc\x44\x24\x0c", "sub": b"\xdc\x64\x24\x0c", "mul": b"\xdc\x4c\x24\x0c",
              "div": b"\xdc\x74\x24\x0c"}
FLOAT_SPECIALS = [0x00000000, 0x80000000, 0x3F800000, 0xBF800000, 0x3FC00000, 0x7F800000, 0xFF800000,
                  0x7FC00000, 0xFFC00000, 0x7FC12345, 0xFFC54321, 0x7FE00000, 0x7F800001, 0xFF812345,
                  0x7F7FFFFF, 0x4B000001]
DOUBLE_SPECIALS = [0x0000000000000000, 0x8000000000000000, 0x3FF0000000000000, 0xBFF0000000000000,
                   0x3FF8000000000000, 0x7FF0000000000000, 0xFFF0000000000000, 0x7FF8000000000000,
                   0xFFF8000000000000, 0x7FF8000012345678, 0xFFF8765432100000, 0x7FFC000000000000,
                   0x7FF0000000000001, 0xFFF0000123456789, 0x7FEFFFFFFFFFFFFF, 0x4330000000000001]


class Oracle:
    def __init__(self):
        self.emu = Emulator().init_crt()
        self.emu.uc.mem_map(CODE, 0x1000, UC_PROT_ALL)
        self.next = CODE

    def code(self, data):
        addr = self.next
        self.emu.mem_write(addr, data)
        self.next += 0x20
        return addr

    def run(self, addr, fpcw, args, out, size):
        emu = self.emu
        emu.uc.reg_write(UC_X86_REG_FPCW, fpcw)
        emu.call(addr, *args, out)
        return emu.mem_read(out, size)


def halves(value):
    return [value & 0xFFFFFFFF, value >> 32]


def main():
    rng = random.Random(87)
    oracle = Oracle()
    emu = oracle.emu
    out = emu.scratch(size=8)
    floats = {op: oracle.code(b"\x8b\x44\x24\x0c\xd9\x44\x24\x04" + code + b"\xd9\x18\xc3")
              for op, code in FLOAT_OPS.items()}
    doubles = {op: oracle.code(b"\x8b\x44\x24\x14\xdd\x44\x24\x04" + code + b"\xdd\x18\xc3")
               for op, code in DOUBLE_OPS.items()}
    float_sqrt = oracle.code(b"\x8b\x44\x24\x08\xd9\x44\x24\x04\xd9\xfa\xd9\x18\xc3")
    double_sqrt = oracle.code(b"\x8b\x44\x24\x0c\xdd\x44\x24\x04\xd9\xfa\xdd\x18\xc3")

    float_pairs = [(a, b) for a in FLOAT_SPECIALS for b in FLOAT_SPECIALS]
    float_pairs += [(struct.unpack("<I", struct.pack("<f", rng.uniform(-1e3, 1e3)))[0],
                     struct.unpack("<I", struct.pack("<f", rng.uniform(-1e3, 1e3)))[0]) for _ in range(64)]
    double_pairs = [(a, b) for a in DOUBLE_SPECIALS for b in DOUBLE_SPECIALS]
    double_pairs += [(struct.unpack("<Q", struct.pack("<d", rng.uniform(-1e3, 1e3)))[0],
                      struct.unpack("<Q", struct.pack("<d", rng.uniform(-1e3, 1e3)))[0]) for _ in range(64)]

    lines = ["// Generated by tools/x87_vectors.py from the x87 in the emulation oracle."]
    lines.append("// {a, b, a + b, a - b, a * b, a / b} as floats under single precision.")
    lines.append("static const FloatOpVector kFloatOps[] = {")
    for a, b in float_pairs:
        r = [struct.unpack("<I", oracle.run(floats[op], 0x007F, (a, b), out, 4))[0] for op in FLOAT_OPS]
        lines.append(f"    {{0x{a:08x}, 0x{b:08x}, {{{', '.join(f'0x{v:08x}' for v in r)}}}}},")
    lines.append("};")
    lines.append("// {a, b, a + b, a - b, a * b, a / b} as doubles under double precision.")
    lines.append("static const DoubleOpVector kDoubleOps[] = {")
    for a, b in double_pairs:
        r = [struct.unpack("<Q", oracle.run(doubles[op], 0x027F, (*halves(a), *halves(b)), out, 8))[0]
             for op in DOUBLE_OPS]
        lines.append(f"    {{0x{a:016x}, 0x{b:016x}, {{{', '.join(f'0x{v:016x}' for v in r)}}}}},")
    lines.append("};")
    lines.append("// {a, the square root} of floats under single precision and doubles under double.")
    lines.append("static const std::uint32_t kFloatSqrts[][2] = {")
    for a in FLOAT_SPECIALS + [0xC0800000, 0x40800000, 0xBF000000]:
        r = struct.unpack("<I", oracle.run(float_sqrt, 0x007F, (a,), out, 4))[0]
        lines.append(f"    {{0x{a:08x}, 0x{r:08x}}},")
    lines.append("};")
    lines.append("static const std::uint64_t kDoubleSqrts[][2] = {")
    for a in DOUBLE_SPECIALS + [0xC010000000000000, 0x4010000000000000, 0xBFE0000000000000]:
        r = struct.unpack("<Q", oracle.run(double_sqrt, 0x027F, halves(a), out, 8))[0]
        lines.append(f"    {{0x{a:016x}, 0x{r:016x}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
