"""Test vectors for the port's states past standing and walking (world::SetGameActorState,
world::SetPlayerState and world::ProcessGameActorState, src/world/actor_state.h), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/enter_vectors.py > tests/unit/enter_vectors.inc

On tools/walk_vectors.py's three small maps, scripts as tools/walk_oracle.py's make_enters makes
them (an actor's and a CPc's vf10 from assorted states, then ProcessState update by update),
with short runs; then on the open field, actors and players whose results each hang on one
thing: state 8 facing a target on its 34th tick and one tick either side, a target not found,
none named, state 4's slide with time left and with none, finished (with +0xd0 too), and a
product just past a tie of single precision; states 2 and 7 played to the end, and state 7
asked in state 6.
The x87 runs at single precision, as in the client.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle  # noqa: E402
import path_vectors  # noqa: E402
import walk_oracle  # noqa: E402
import walk_vectors  # noqa: E402

TICK_MS = 24  # 1/24 of a millisecond counts a tick, 005e9000
SLIDE_WAY, SLIDE_GONE = "0x32000003", 1848289963


def deciding(actor, player):
    """Actors and players made from a generated E and Q line, not held and no fade, each set or
    left in a state whose result hangs on one thing."""
    lines = []
    for template, kind, n in ((actor, "E", 39), (player, "Q", 44)):
        tokens = template.split()
        fields, enter, times = tokens[1:1 + n], tokens[1 + n:1 + n + 9], tokens[1 + n + 9:]
        fields[11], fields[12], fields[14], fields[19] = "0", "0", "0", "0"
        tick = int(times[1])
        updates = times[2:12]

        def line(before, set_state, state, target, found, start, play="0", finished="0", run=updates, frames=None,
                 blocked="0", edit=None):
            f, e = list(fields), list(enter)
            f[17], f[36], f[19] = str(before), finished, blocked
            if frames is not None:
                f[10] = str(frames)
            if edit:
                edit(f)
            e[0], e[1], e[2], e[3], e[4], e[7], e[8] = (str(set_state), str(state), "1", str(target),
                                                       str(found), play, str(start & 0xFFFFFFFF))
            return f"{kind} " + " ".join(f + e + times[:2] + run)

        # State 8 left in, its target due at the update's tick (34 of them), one tick before and
        # after, then not found and not named.
        first = int(updates[1])
        for gone in (34 * 34 * TICK_MS, 34 * TICK_MS, 34 * TICK_MS - 1, 35 * TICK_MS, 0):
            lines.append(line(8, 0, 0, 4321, 1, first - gone, run=updates[:2]))
        lines.append(line(8, 0, 0, 4321, 0, first - 34 * TICK_MS, run=updates[:2]))
        lines.append(line(8, 0, 0, 0, 1, first - 34 * TICK_MS, run=updates[:2]))
        # State 4 left in, its action looping: 200 ms still to go, 1 ms, none, long gone; then
        # played once, and finished.
        for start in (tick, tick - 199, tick - 200, tick - 5000):
            lines.append(line(4, 0, 0, 0, 0, start))
        lines.append(line(4, 0, 0, 0, 0, tick, play="1"))
        lines.append(line(4, 0, 0, 0, 0, tick, play="1", finished="1"))
        # Finished with +0xd0 set, so that standing again does nothing: the slide alone puts the
        # actor on its target.
        lines.append(line(4, 0, 0, 0, 0, tick, play="1", finished="1", blocked="1"))

        # From x 0 to a target 2^-27 × 0x800003 away, 1,848,289,963 ms gone and 1 left: the way
        # times the time gone lies just past a tie of single precision, so rounding it through a
        # double first lands one ulp lower.
        def tie(f):
            f[0], f[25], f[26] = "0x00000000", SLIDE_WAY, f[1]
            f[16] = str((first - SLIDE_GONE) & 0xFFFFFFFF)
        lines.append(line(4, 0, 0, 0, 0, first - 199, run=updates[:2], edit=tie))
        # Left in 2 and 7, played once to the end.
        for state in (2, 7):
            lines.append(line(state, 0, 0, 0, 0, tick, play="1", run=times[2:], frames=2))
        # State 7 in state 6 does nothing; 5, 11 and 12 played once to the end, two frames long.
        lines.append(line(6, 1, 7, 0, 0, tick))
        for state in (5, 11, 12):
            lines.append(line(0, 1, state, 0, 0, tick, run=times[2:], frames=2))
    return lines


def main():
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/enter_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's searches")
    lines.append("// and actors given states in order (tools/walk_oracle.py's script and output), then chosen")
    lines.append("// ones.")
    lines.append("static const StateQueryVector kEnterQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_enters(name, width, height, attrs, 30, updates=(4, 12, 30, 80))
        if name == "open":
            script += deciding(next(q for q in script if q[0] == "E" and len(q.split()) > 1 + 39 + 9 + 12),
                               next(q for q in script if q[0] == "Q" and len(q.split()) > 1 + 44 + 9 + 12))
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
