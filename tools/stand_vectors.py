"""Test vectors for the port's standing actors (world::ProcessStand, src/world/actor_state.h),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/stand_vectors.py > tests/unit/stand_vectors.inc

On tools/walk_vectors.py's three small maps, scripts as tools/walk_oracle.py's make_stands makes
them (CGameActor::ProcessState on actors and players standing), with short runs; then on the
open field, standing actors whose results each hang on one thing: a pet whose talk is due and
whose rand() % 100 is below 25, one whose is not, one whose is just 25, a job of 999 that would
talk, and an action played once and finished.
The x87 runs at single precision, as in the client.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle
import path_vectors
import walk_oracle
import walk_vectors


def first_rand(seed):
    """The C runtime's first rand() after srand(seed)."""
    return ((seed * 0x343FD + 0x269EC3) & 0xFFFFFFFF) >> 16 & 0x7FFF


def deciding(template):
    """Standing actors made from a generated N line: a monster pet (job 1001, +0x1f4 20, its id
    the pet's) whose talk is 3001 ms due, with a seed that talks and one that does not, and an
    action played once and finished. No hold and no fade."""
    tokens = template.split()
    fields, times = tokens[1:47], tokens[47:]
    fields[7], fields[11], fields[12], fields[17], fields[19] = "1001", "0", "0", "0", "0"
    fields[34] = fields[40] = "4321"
    fields[45] = "20"
    fields[43] = str((int(times[1]) - 3001) & 0xFFFFFFFF)
    talks = next(s for s in range(1, 1000) if first_rand(s) % 100 < 25)
    quiet = next(s for s in range(1, 1000) if first_rand(s) % 100 >= 25)
    lines = []
    for seed in (talks, quiet):
        f = list(fields)
        f[39], f[44], f[36] = str(seed), "0", "0"
        lines.append("N " + " ".join(f + times[:8]))
    f = list(fields)
    f[39], f[44], f[36], f[43] = str(quiet), "1", "1", "0"
    lines.append("N " + " ".join(f + times[:8]))
    # A seed whose rand() % 100 is just 25, and a job just below the pets' with one that talks.
    f = list(fields)
    f[39], f[44], f[36] = str(next(s for s in range(1, 100000) if first_rand(s) % 100 == 25)), "0", "0"
    lines.append("N " + " ".join(f + times[:8]))
    f = list(fields)
    f[7], f[39], f[44], f[36] = "999", str(talks), "0", "0"
    lines.append("N " + " ".join(f + times[:8]))
    return lines


def main():
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/stand_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's searches")
    lines.append("// and standing actors in order (tools/walk_oracle.py's script and output), then chosen ones.")
    lines.append("static const StateQueryVector kStandQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_stands(name, width, height, attrs, 30, updates=(4, 12, 30, 80))
        if name == "open":
            script += deciding(next(line for line in script if line[0] == "N"))
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
