"""Test vectors for the port's __ftol (core::Ftol, src/core/x87.h), taken from the original in
the emulation oracle.

usage: .venv/bin/python -I tools/ftol_vectors.py > tests/unit/ftol_vectors.inc

__ftol (005c2084) runs on doubles loaded by a stub on a page of its own (fld qword, call,
ret): zero and the signs, fractions toward zero, the edges of 32 and 64 bits on both sides, large and huge
values, the infinities, NaNs, denormals, and assorted values, as doubles and as floats
widened. Each vector keeps the 64 bits it leaves in EDX:EAX; the port returns EAX.
"""
import math
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn import UC_PROT_ALL

from emu import Emulator

FTOL = 0x5C2084
# A page mapped for the stub alone, executable where the scratch memory is not.
STUB_PAGE = 0x7E000000


def doubles(rng):
    edges = [0.0, -0.0, 0.5, -0.5, 0.999999, -0.999999, 1.0, -1.0, 1.5, -1.5, 2.5, -2.5,
             2147483647.0, 2147483647.5, 2147483648.0, -2147483648.0, -2147483648.5, -2147483649.0,
             4294967295.0, 4294967296.0, 4294967297.5, -4294967296.0, 1e10, -1e10, 1e15, 2.0 ** 52 + 0.5,
             2.0 ** 53, 2.0 ** 62, 2.0 ** 63 - 1024, 2.0 ** 63, -(2.0 ** 63), -(2.0 ** 63) - 2048,
             2.0 ** 64, 1e19, -1e19, 1e300, -1e300, math.inf, -math.inf, math.nan, -math.nan,
             5e-324, -5e-324, 2.2250738585072014e-308]
    out = list(edges)
    for _ in range(80):
        out.append(rng.choice([rng.uniform(-1e3, 1e3), rng.uniform(-3e9, 3e9), rng.uniform(-1e12, 1e12),
                               rng.uniform(-1e20, 1e20), rng.uniform(-1, 1)]))
    for _ in range(40):
        out.append(struct.unpack("<f", struct.pack("<f", rng.choice([rng.uniform(-3e9, 3e9), rng.uniform(-1e20, 1e20),
                                                                    rng.uniform(-100, 100)])))[0])
    out.append(struct.unpack("<d", struct.pack("<Q", 0x7FF4000000000000))[0])
    return out


def main():
    emu = Emulator().init_crt()
    stub = STUB_PAGE
    emu.uc.mem_map(stub, 0x1000, UC_PROT_ALL)
    rel = FTOL - (stub + 4 + 5)
    emu.mem_write(stub, b"\xDD\x44\x24\x04" + b"\xE8" + struct.pack("<i", rel) + b"\xC3")
    lines = ["// Generated by tools/ftol_vectors.py from the original in the emulation oracle.",
             "// __ftol (005c2084): {the double's bits, EDX:EAX after}.",
             "static const std::uint64_t kFtols[][2] = {"]
    for v in doubles(random.Random(1907)):
        b = struct.unpack("<Q", struct.pack("<d", v))[0]
        r = emu.call(stub, b & 0xFFFFFFFF, b >> 32)
        lines.append(f"    {{0x{b:016x}ull, 0x{(r.edx << 32) | r.eax:016x}ull}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
