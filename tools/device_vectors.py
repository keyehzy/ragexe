"""Test vectors for the port's device set-up (docs/render/device.md), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/device_vectors.py > tests/unit/device_vectors.inc

  - C3dDevice::Init (00404410), windowed and full screen, on a HAL and a T&L HAL device,
    with the desktop in each 16- and 32-bit format: the render and texture stage states
    it sets, in order, and the channel shifts and losses it derives from the primary
    surface's pixel format.
  - The channel expanders 00405df0, 00405e20 and 00405e50 on sample pixels, with the
    shifts each Init left.
  - FitTextureSize (004056e0) for sizes against device texture limits.
  - SelectMipmapFlags (00405f20) for the TRILINEARFILTER setting and the filter caps.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402
from emu.directx import PF_555, PF_565, PF_8888, PF_X888  # noqa: E402
from emu.winapi import WINDOW  # noqa: E402

CTOR, INIT, SIZE = 0x404240, 0x404410, 0x268
EXPAND_RED, EXPAND_GREEN, EXPAND_BLUE = 0x405DF0, 0x405E20, 0x405E50
FIT_TEXTURE_SIZE, SELECT_MIPMAP_FLAGS = 0x4056E0, 0x405F20
IID_HAL_DEVICE, IID_TNL_HAL_DEVICE = 0x5EC118, 0x5EC0D8
TRILINEAR_SETTING, MIPMAP_DESC_FLAGS, MIPMAP_CAPS = 0x688504, 0x623C10, 0x623C14
FORMATS = {"565": PF_565, "555": PF_555, "x888": PF_X888, "8888": PF_8888}
PIXELS = [0, 0xFFFF, 0xF800, 0x07E0, 0x001F, 0x7C00, 0x03E0, 0x8000, 0x1234, 0xABCD, 0xFFFFFFFF, 0x00FF8040]


def init(windowed, pf, device):
    emu = Emulator()
    emu.directx.profile.display = (800, 600, pf)
    dev = emu.scratch(size=SIZE)
    emu.call(CTOR, this=dev)
    mode = 0
    if not windowed:
        desc = bytearray(0x7C)
        struct.pack_into("<IIII", desc, 0, 0x7C, 0x1006, 600, 800)
        struct.pack_into("<I", desc, 0x54, struct.unpack_from("<I", pf, 12)[0])
        mode = emu.scratch(bytes(desc))
    result = emu.call(INIT, WINDOW, 0, device, mode, 6 if windowed else 7, this=dev).signed
    assert result == 0, hex(result)
    calls = []
    for c in emu.directx.calls:
        if c.method == "SetRenderState":
            calls.append((-1, c.args[0], c.args[1]))
        elif c.method == "SetTextureStageState":
            calls.append(tuple(c.args))
    return emu, dev, calls


def main():
    print("// Generated by tools/device_vectors.py from the original in the emulation oracle.")
    variants = []
    for windowed in (True, False):
        # Full screen, the format comes with the display mode the driver sets: the fakes
        # give the first one of the bit count.
        for fmt, pf in FORMATS.items() if windowed else (("565", PF_565), ("x888", PF_X888)):
            for device, device_name in ((IID_HAL_DEVICE, "HAL"), (IID_TNL_HAL_DEVICE, "TnL HAL")):
                variants.append((f"{'windowed' if windowed else 'full screen'}, {fmt}, {device_name}",
                                 *init(windowed, pf, device)))
    for k, (_, _, _, calls) in enumerate(variants):
        print(f"static const StateCall kInitCalls{k}[] = {{")
        for stage, state, value in calls:
            print(f"    {{{stage}, {state}, 0x{value:x}}},")
        print("};")
    print("// {name, calls, bits, masks, shifts, losses}: what Init left for each.")
    print("static const InitVector kInitVectors[] = {")
    for k, (name, emu, dev, _) in enumerate(variants):
        u = emu.read_u32
        signed = [v - (1 << 32) if v & 0x80000000 else v for v in (u(dev + 0x1F0 + 4 * i) for i in range(8))]
        masks = ", ".join(f"0x{u(dev + o):x}" for o in (0x214, 0x218, 0x21C, 0x220))
        print(f'    {{"{name}", kInitCalls{k}, std::size(kInitCalls{k}), {u(dev + 0x210)}, {{{masks}}}, '
              f'{{{signed[0]}, {signed[2]}, {signed[4]}, {signed[6]}}}, '
              f'{{{signed[1]}, {signed[3]}, {signed[5]}, {signed[7]}}}}},')
    print("};")
    print("// {Init vector, pixel, red, green, blue}: 00405df0, 00405e20 and 00405e50.")
    print("static const ExpandVector kExpandVectors[] = {")
    for k, (_, emu, dev, _) in enumerate(variants):
        if k % 2:
            continue
        for p in PIXELS:
            r, g, b = (emu.call(f, p, this=dev).eax for f in (EXPAND_RED, EXPAND_GREEN, EXPAND_BLUE))
            print(f"    {{{k}, 0x{p:x}, {r}, {g}, {b}}},")
    print("};")

    emu = Emulator()
    dev = emu.scratch(size=SIZE)
    sizes = [0, 1, 2, 3, 5, 64, 100, 127, 128, 129, 300, 1000, 4096]
    limits = [(1, 1, 2048, 2048, 0), (1, 1, 256, 256, 1), (8, 8, 1024, 1024, 8), (1, 1, 2048, 2048, 2),
              (16, 4, 512, 128, 4)]
    print("// {min width, min height, max width, max height, max aspect, width, height, fitted width,")
    print("// fitted height}: 004056e0.")
    print("static const FitVector kFitVectors[] = {")
    for lim in limits:
        for o, v in zip((0x224, 0x228, 0x22C, 0x230, 0x234), lim):
            emu.write_u32(dev + o, v)
        for w in sizes:
            for h in sizes:
                pw, ph = emu.scratch(struct.pack("<I", w)), emu.scratch(struct.pack("<I", h))
                emu.call(FIT_TEXTURE_SIZE, pw, ph, this=dev)
                print(f"    {{{', '.join(map(str, lim))}, {w}, {h}, {emu.read_u32(pw)}, {emu.read_u32(ph)}}},")
    print("};")
    print("// {TRILINEARFILTER, texture filter caps, surface description flags, surface caps}: 00405f20.")
    print("static const MipmapVector kMipmapVectors[] = {")
    for setting in (0, 1, 2):
        for caps in (0, 0x20, 0x1F, 0x3F, 0xFFFFFFFF):
            emu.write_u32(TRILINEAR_SETTING, setting)
            emu.write_u32(dev + 0xA8, caps)
            emu.call(SELECT_MIPMAP_FLAGS, this=dev)
            print(f"    {{{setting}, 0x{caps:x}, 0x{emu.read_u32(MIPMAP_DESC_FLAGS):x}, "
                  f"0x{emu.read_u32(MIPMAP_CAPS):x}}},")
    print("};")


if __name__ == "__main__":
    main()
