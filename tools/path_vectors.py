"""Test vectors for the port's path finder (src/world/path_finder.h), taken from the original in
the emulation oracle.

usage: .venv/bin/python -I tools/path_vectors.py > tests/unit/path_vectors.inc

Small attribute maps drawn here (an open field, walls of attributes 1 and 5 among the walkable
3 and 6, gaps that only a diagonal could pass, a closed room, a random maze, a field too wide
to cross with 149 nodes), each with a script of queries run as tools/path_oracle.py runs them:
PathFinder::FindPath, CGameActor::FindMovePath, CGameMode::IsPathFound and
MovePath::FindSegment, on one finder and one actor's path, with the path's +0x10 set between
them ("Z value"). Each vector keeps the whole path after its query.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle  # noqa: E402

ATTRIBUTES = {".": 0, "#": 1, "o": 5, "3": 3, "6": 6}

MAPS = [
    ("open", ["." * 12] * 10),
    ("walls", [
        "..........",
        "..######..",
        "..#....#..",
        "..#.33.#..",
        "..#.66.o..",
        "..#....o..",
        "..##.###..",
        "..........",
    ]),
    ("gaps", [
        ".#....",
        "#.#...",
        "..#.#.",
        "...#..",
        "..#.#.",
        "......",
    ]),
    ("room", [
        "........",
        ".######.",
        ".#....#.",
        ".#....#.",
        ".######.",
        "........",
    ]),
    ("wide", ["." * 40] * 40),
]


# Queries whose results hang on one detail each, found by running the port against
# variants of it: a tie in the heap, a reopened cell, the costs, the order of the
# neighbours, the 149th node, the diagonal's 1.414, a path ending just at the server's time
# (736), +0x10 set before a search and kept by one from a cell to itself, and an off-map
# start whose key is (11, 3)'s.
DECIDING = {
    "open": [
        "M 85570 93995 1 4 8 4 4 8 999",
        "F 100 1 1 8 8 4 4 150", "S 4294967295", "M 100 736 1 1 8 8 4 4 150",
        "Z 7", "F 0 1 1 8 8 3 3 150", "Z 9", "F 0 2 2 8 8 2 2 150",
        "F 10 -1 4 8 8 11 3 150", "F 10 -1 4 8 8 11 2 150",
    ],
    "walls": ["F 9720 0 1 8 5 9 6 150", "F 2440214953 0 4 -18 -20 9 3 75", "F 95111 0 6 0 8 8 1 300",
              "F 40720 0 3 8 0 8 4 999"],
    "maze": ["F 4294967265 23 8 0 33 7 9 300", "F 681337578 21 9 8 8 23 2 200"],
    "wide": ["M 421690745 421690745 3 3 8 15 24 37 150", "F 1631131957 1 39 0 0 34 15 200"],
}


def maze(rng, width, height, share):
    return ["".join("#" if rng.random() < share else "." for _ in range(width)) for _ in range(height)]


def gat(rows):
    width, height = len(rows[0]), len(rows)
    data = bytearray(b"GRAT\x01\x02" + struct.pack("<ii", width, height))
    for row in rows:
        for c in row:
            data += struct.pack("<4fi", 0.0, 0.0, 0.0, 0.0, ATTRIBUTES[c])
    return bytes(data)


def scripts(rng):
    """The queries for each map: chosen cases, then the oracle's own mix."""
    out = {}
    out["open"] = [
        "F 1000 1 1 8 8 5 1 150", "S 999", "S 1000", "S 1075", "S 1700", "S 4000000000",
        "F 2000 1 1 0 0 6 6 150", "F 2000 0 0 15 15 3 2 100", "F 0 0 3 4 12 0 3 150",
        "F 5 2 2 -5 30 2 2 150", "F 7 2 2 8 8 9 4 7",
        "M 100 100 1 1 8 8 4 4 150", "M 100 20000 1 1 8 8 4 4 150", "M 4294967000 50 1 1 8 8 9 2 200",
        "I 77 1 1 8 8 10 9", "I 77 3 3 8 8 3 3",
        "F 10 -1 4 8 8 2 4 150", "F 10 12 4 8 8 9 4 150", "F 10 3 -2 8 8 3 3 150",
        "F 4294967290 11 9 8 8 0 0 999",
    ]
    out["walls"] = [
        "F 0 4 3 8 8 0 0 150", "S 100", "S 300", "F 0 0 0 8 8 4 4 150", "F 0 0 0 8 8 5 5 150",
        "F 0 9 7 8 8 4 3 150", "F 0 4 0 8 8 7 5 150", "F 0 8 4 8 8 4 4 150",
        "F 0 4 3 8 8 4 3 150", "M 0 0 0 0 8 8 4 4 120", "S 50",
    ]
    out["gaps"] = [
        "F 0 0 0 8 8 1 1 150", "F 0 1 1 8 8 3 0 150", "F 0 3 2 8 8 4 3 150", "F 0 0 5 8 8 5 0 150",
        "F 0 3 4 8 8 5 5 150", "S 0", "S 400",
    ]
    out["room"] = [
        "F 0 0 0 8 8 3 2 150", "F 0 3 2 8 8 0 0 150", "F 0 3 2 8 8 4 3 150", "F 0 0 0 8 8 7 5 150",
        "I 0 0 0 8 8 3 3",
    ]
    out["wide"] = [
        "F 0 2 2 8 8 37 37 150", "F 0 2 2 8 8 9 2 150", "F 0 2 2 8 8 2 14 150", "F 0 20 20 8 8 22 23 150",
        "M 0 0 2 2 8 8 30 2 150", "I 0 2 2 8 8 37 37",
    ]
    rows = {name: r for name, r in MAPS}
    rows["maze"] = maze(rng, 24, 20, 0.3)
    out["maze"] = []
    for name, r in rows.items():
        width, height = len(r[0]), len(r)
        attrs = [ATTRIBUTES[c] for row in r for c in row]
        out[name] += path_oracle.make_queries(name, width, height, attrs, 25) + DECIDING.get(name, [])
    return rows, out


def main():
    rng = random.Random(1907)
    rows, queries = scripts(rng)
    oracle = path_oracle.Oracle()
    lines = ["// Generated by tools/path_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps, a row at a time from y = 0: '.' attribute 0, '#' 1, 'o' 5, '3' 3, '6' 6.")
    lines.append("static const PathMapVector kPathMaps[] = {")
    for name, r in rows.items():
        lines.append(f"    {{\"{name}\", {len(r[0])}, {len(r)}, \"{''.join(r)}\"}},")
    lines.append("};")
    lines.append("// Each map's queries in order, on one finder and one path (tools/path_oracle.py's script")
    lines.append("// and output); found and failed searches keep the whole path, as x y dir time per step.")
    lines.append("static const PathQueryVector kPathQueries[] = {")
    for m, name in enumerate(rows):
        script = queries[name]
        results = oracle.run(gat(rows[name]), script)
        paths = iter(oracle.paths)
        for query, result in zip(script, results):
            steps = " ".join(str(v) for v in next(paths)) if query[0] in "FM" else ""
            lines.append(f"    {{{m}, \"{query}\", \"{result}\", \"{steps}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
