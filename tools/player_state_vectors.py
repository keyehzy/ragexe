"""Test vectors for the port's player states (world::SetPlayerState, src/world/actor_state.h),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/player_state_vectors.py > tests/unit/player_state_vectors.inc

On tools/walk_vectors.py's three small maps, scripts of searches and player moves as
tools/walk_oracle.py makes them (P: CGameActor::SendMsg's message 0 to a CPc, then
CGameActor::ProcessState update by update with CPc::SetState run, to standing), with short walks.
The x87 runs at single precision, as in the client.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle  # noqa: E402
import path_vectors  # noqa: E402
import walk_oracle  # noqa: E402
import walk_vectors  # noqa: E402


def main():
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/player_state_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's searches")
    lines.append("// and player moves in order, on one finder and one path (tools/walk_oracle.py's script")
    lines.append("// and output).")
    lines.append("static const StateQueryVector kPlayerStateQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_plays(name, width, height, attrs, 30, updates=(4, 12, 30, 80))
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
