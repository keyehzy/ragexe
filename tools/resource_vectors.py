"""Test vectors for MakeDataPath, taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/resource_vectors.py > tests/unit/resource_vectors.inc
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402

MAKE_DATA_PATH = 0x4DD5A0  # analysis/labels/inferred.functions.tsv

NAMES = [
    "", "a.bmp", "texture\\Prontera.BMP", "ResNameTable.txt", "C:\\abs\\x.bmp",
    "texture\\x:y.bmp", "a//b.bmp", "a///b////c.bmp", "..\\_tmpEmblem\\e.ebm",
    "sprite/mixed\\sep.spr", "//lead.bmp", "x\\:.bmp",
]


def escape(s):
    return "".join(c if c.isalnum() or c in "._ " else f"\\{ord(c):03o}" for c in s)


def main():
    emu = Emulator().init_crt()
    print("// Generated by tools/resource_vectors.py from the original in the emulation oracle.")
    print("// {name, MakeDataPath(name)}")
    print("static const PathVector kPathVectors[] = {")
    for name in NAMES:
        dst = emu.scratch(size=1024)
        emu.call(MAKE_DATA_PATH, dst, emu.cstr(name))
        print(f'    {{"{escape(name)}", "{escape(emu.read_cstr(dst))}"}},')
    print("};")


if __name__ == "__main__":
    main()
