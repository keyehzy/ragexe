"""Test vectors for the actors' constructors (world::MakeNpc and world::MakePlayerActor,
src/world/actor_walk.h and actor_state.h), taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/actor_make_vectors.py > tests/unit/actor_make_vectors.inc

CNpc's constructor (0053f950) and CPc's (00541fb0) on memory filled first with one byte and then
another, CRenderObject::SetSprite (005018a0) and SetAct (00501910) stood in for (the names they
are given, from the job names at 00686dc8, are not kept by the port), at assorted times (timeGetTime) and server time offsets (ClientState+0x504, which
ClientState::GetServerTime, 00593200, takes from timeGetTime less 72). Each field the port keeps
is recorded with whether the constructor set it: a field that differs between the two fillings
was left as the memory had it.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu.emulator import Emulator
from emu.winapi import Stub

NPC_CTOR, NPC_SIZE = 0x53F950, 0x298
PC_CTOR, PC_SIZE = 0x541FB0, 0x308
G_CLIENT_STATE, SERVER_OFFSET = 0x686670, 0x504
SET_SPRITE, SET_ACT, JOB_NAMES = 0x5018A0, 0x501910, 0x686DC8
FILLS = (0x00, 0xA5)
TIMES = [(1000000, 0), (0, 0), (3000, 12345), (0xFFFFFFFF, 0xFFFFFFB8), (0x7FFFF000, 0x80000000)]

# The fields the port keeps, as (offset, size): CRenderObject's (render::RenderObject), then
# CGameActor's (world::GameActor), then CPc's (world::PlayerActor). Their order is the test's.
OBJECT_FIELDS = [(0x4, 4), (0x8, 4), (0xC, 4), (0x20, 4), (0x24, 4), (0x28, 4), (0x2C, 4), (0x30, 4),
                 (0x38, 4), (0x3C, 4), (0x40, 4), (0x5C, 4), (0x60, 4), (0x64, 4), (0x44, 4), (0x48, 4),
                 (0x50, 4), (0x4C, 4), (0x54, 4), (0x68, 4), (0x6C, 4), (0x70, 4), (0x7C, 4), (0x80, 1),
                 (0x81, 1), (0x82, 1), (0x83, 1), (0x84, 1), (0x85, 1), (0x86, 1), (0x87, 1), (0x89, 1),
                 (0x88, 1), (0x90, 4), (0x94, 4)]
ACTOR_FIELDS = [(0x58, 4), (0xA8, 4), (0xC0, 4), (0xC4, 4), (0xC8, 4), (0xCC, 4), (0xD0, 4), (0xD8, 4),
                (0x18C, 4), (0x190, 1), (0x194, 4), (0x198, 4), (0x19C, 4), (0x1A0, 4), (0x1A4, 4),
                (0x1A8, 4), (0x1AC, 4), (0x1B4, 4), (0x1B8, 4), (0x1BC, 4), (0x1C0, 4), (0x1C4, 4),
                (0x1C8, 4), (0x1CC, 4), (0x1D0, 4), (0x1D4, 4), (0x1D8, 4), (0x1DC, 4), (0x1E0, 4),
                (0x1E4, 4), (0x1EC, 4), (0x1F0, 4), (0x1F4, 4), (0x210, 4), (0x218, 4), (0x21C, 4),
                (0x220, 4), (0x224, 4), (0x228, 4), (0x22C, 4), (0x230, 4), (0x234, 4), (0x238, 4),
                (0x23C, 4), (0x240, 4)] + [(0x244 + 4 * k, 4) for k in range(11)] + [(0x290, 4)]
PC_FIELDS = [(0x28C, 4), (0x294, 4), (0x2A0, 4), (0x2DC, 4), (0x2E0, 4), (0x2E4, 4)]


def construct(emu, now, offset, ctor, size, fill, fields):
    emu.api.stubs["WINMM.DLL!timeGetTime"] = Stub(0, lambda: now)
    emu.write_u32(G_CLIENT_STATE + SERVER_OFFSET, offset)
    actor = emu.alloc(size)
    emu.mem_write(actor, bytes([fill]) * size)
    emu.call(ctor, this=actor)
    return [int.from_bytes(emu.mem_read(actor + o, n), "little") for o, n in fields]


def main():
    emu = Emulator().init_crt()
    names = emu.scratch(size=0x400)
    for k in range(0, 0x400, 4):
        emu.write_u32(names + k, emu.cstr("x"))
    emu.write_u32(JOB_NAMES, names)
    emu.replace_thiscall(SET_SPRITE, 1, lambda this, name: 0)
    emu.replace_thiscall(SET_ACT, 1, lambda this, name: 0)
    lines = [
        "// Generated by tools/actor_make_vectors.py from the original in the emulation oracle.",
        "// CNpc's constructor (0053f950, kind 0) and CPc's (00541fb0, kind 1): {kind, timeGetTime,",
        "// ClientState+0x504}, the count of the fields kActorMakeOffsets names, which of them it set",
        "// ('1' set, '0' left as the memory had it), and their values.",
        "static const std::uint32_t kActorMakeOffsets[] = {",
    ]
    fields = OBJECT_FIELDS + ACTOR_FIELDS + PC_FIELDS
    for k in range(0, len(fields), 10):
        lines.append("    " + ", ".join(f"0x{o:x}" for o, _ in fields[k:k + 10]) + ",")
    lines += ["};", "static const ActorMakeVector kActorMakes[] = {"]
    for kind, (ctor, size, kept) in enumerate(((NPC_CTOR, NPC_SIZE, OBJECT_FIELDS + ACTOR_FIELDS),
                                               (PC_CTOR, PC_SIZE, fields))):
        for now, offset in TIMES:
            first, second = (construct(emu, now, offset, ctor, size, fill, kept) for fill in FILLS)
            set_ = "".join("1" if a == b else "0" for a, b in zip(first, second))
            values = ", ".join(f"0x{v:x}" for v in first)
            lines.append(f'    {{{kind}, 0x{now:x}, 0x{offset:x}, {len(kept)}, "{set_}",\n     {{{values}}}}},')
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
