"""Test vectors for the port's actor states and moves (src/world/actor_state.h), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/state_vectors.py > tests/unit/state_vectors.inc

  - Moves: on tools/walk_vectors.py's three small maps, scripts of searches and moves as
    tools/walk_oracle.py makes them (CGameActor::vf02's message 0, then CGameActor::ProcessState
    update by update with SetState run, to standing), with short walks.
  - CGameMode::GetAttrCell (00511d50) at points on and either side of the cells' edges, both
    sides of 0 and beyond the map, on a map 12 by 10 cells and one 7 by 5.
The x87 runs at single precision, as in the client.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle  # noqa: E402
import path_vectors  # noqa: E402
import walk_oracle  # noqa: E402
import walk_vectors  # noqa: E402

GET_ATTR_CELL = 0x511D50


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def step(x, n):
    """x moved n float steps up."""
    b = bits(f32(x)) & 0x7FFFFFFF
    i = (b if x > 0 else -b) + n
    return struct.unpack("<f", struct.pack("<I", i if i >= 0 else (-i | 0x80000000)))[0]


def main():
    rng = random.Random(1907)
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/state_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps).")
    lines.append("// Each map's searches and moves in order, on one finder and one path (tools/walk_oracle.py's")
    lines.append("// script and output).")
    lines.append("static const StateQueryVector kStateQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_goes(name, width, height, attrs, 30, updates=(4, 12, 30, 80))
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    lines.append("// CGameMode::GetAttrCell (00511d50): {width, height, x, z (float bits), the cell}.")
    lines.append("static const AttrCellVector kAttrCells[] = {")
    emu = oracle.emu
    out = emu.scratch(size=8)
    for width, height in ((12, 10), (7, 5)):
        emu.serve_data_files({"data\\t.gat": walk_vectors.gat(["." * width] * height, False)})
        emu.mem_write(oracle.attr, bytes(0x12C))
        emu.call(path_oracle.C3DATTR_CTOR, this=oracle.attr)
        emu.call(path_oracle.C3DATTR_LOAD, emu.cstr("t.gat"), this=oracle.attr)
        points = []
        for edge in (-30.0, -15.0, -5.0, -2.5, 0.0, 2.5, 5.0, 12.5, 25.0, 30.0, 40.0):
            for n in (-1, 0, 1):
                points.append(f32(step(edge, n)))
        points += [f32(rng.uniform(-60, 60)) for _ in range(12)]
        for x in points:
            z = rng.choice(points)
            emu.call(GET_ATTR_CELL, bits(x), bits(z), out, out + 4, this=oracle.mode)
            cx, cz = struct.unpack("<2i", emu.mem_read(out, 8))
            lines.append(f"    {{{width}, {height}, 0x{bits(x):08x}, 0x{bits(z):08x}, {cx}, {cz}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
