"""Test vectors for the port's matrices and keys (src/render/matrix.h, docs/render/model.md),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/matrix_vectors.py > tests/unit/matrix_vectors.inc

Each runs under single precision (control word 0x7f, as DirectDraw's FPUSETUP leaves the
client's main thread) and double precision (0x27f, the CRT's default, which
LazyModelLoadThread starts with):
  - Matrix::Multiply (00409d90) and Matrix::Invert (00409ed0) of random matrices, some
    with a zero row, and Matrix::MakeRotationFromKey (00409ae0) of random quaternions, unit
    and not;
  - TranslationKeys::GetMatrixAt (00401520) and RotationKeys::GetMatrixAt (00401d10) on
    tracks of two to four keys, at times before, on and between the keys (not past the last,
    where the original reads beyond its keys), with some rotation pairs whose w is exactly 1;
  - SqrtFloat (00409570) of zeros, infinities, NaNs, negatives and assorted numbers, and
    SinFloat (00409580) and CosFloat (00409590) of zeros and assorted angles, each stored by
    a caller's fstp. (The emulator's fsin and fcos leave an infinity as it is, where the x87
    gives the real indefinite, so their infinities and NaNs are left out.)
"""
import math
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn import UC_PROT_ALL  # noqa: E402
from unicorn.x86_const import UC_X86_REG_FPCW  # noqa: E402

from emu import Emulator  # noqa: E402

MULTIPLY, INVERT, ROTATION_FROM_KEY = 0x409D90, 0x409ED0, 0x409AE0
TRANSLATION_AT, ROTATION_AT = 0x401520, 0x401D10
SQRT_FLOAT, SIN_FLOAT, COS_FLOAT = 0x409570, 0x409580, 0x409590
PRECISIONS = (0x007F, 0x027F)
CODE = 0x7F000000


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(f):
    return struct.unpack("<I", struct.pack("<f", f))[0]


def hexes(values):
    return ", ".join(f"0x{v:08x}" for v in values)


def matrix(rng):
    m = [f32(rng.uniform(-2, 2)) for _ in range(9)] + [f32(rng.uniform(-500, 500)) for _ in range(3)]
    if rng.random() < 0.15:
        row = rng.randrange(3)
        m[row * 3:row * 3 + 3] = [0.0, 0.0, 0.0]
    return m


def quaternion(rng, unit=True):
    q = [rng.uniform(-1, 1) for _ in range(4)]
    n = math.sqrt(sum(c * c for c in q)) if unit else rng.uniform(0.5, 2.0)
    return [f32(c / n) for c in q]


class Oracle:
    def __init__(self):
        self.emu = Emulator().init_crt()
        self.out = self.emu.scratch(size=48)

    def matrix_call(self, fpcw, addr, *args):
        emu = self.emu
        emu.uc.reg_write(UC_X86_REG_FPCW, fpcw)
        emu.call(addr, *args, this=self.out)
        return list(struct.unpack("<12I", emu.mem_read(self.out, 48)))

    def track(self, keys, size):
        """A key vector as TranslationKeys and RotationKeys keep it: begin at +4, end at +8."""
        data = b"".join(keys)
        begin = self.emu.scratch(data)
        return self.emu.scratch(struct.pack("<3I", 0, begin, begin + len(keys) * size))


def track_frames(rng, count):
    frames = [rng.randint(-50, 50)]
    for _ in range(count - 1):
        frames.append(frames[-1] + rng.randint(1, 400))
    return frames


def main():
    rng = random.Random(409)
    oracle = Oracle()
    emu = oracle.emu
    lines = ["// Generated by tools/matrix_vectors.py from the original in the emulation oracle."]

    lines.append("// {a, b, a · b and a's inverse at single precision, then at double}.")
    lines.append("static const MatrixVector kMatrixVectors[] = {")
    for _ in range(300):
        a, b = matrix(rng), matrix(rng)
        pa = emu.scratch(struct.pack("<12f", *a))
        pb = emu.scratch(struct.pack("<12f", *b))
        products = [oracle.matrix_call(p, MULTIPLY, pa, pb) for p in PRECISIONS]
        inverses = [oracle.matrix_call(p, INVERT, pa) for p in PRECISIONS]
        lines.append(f"    {{{{{hexes(bits(v) for v in a)}}},\n     {{{hexes(bits(v) for v in b)}}},\n"
                     f"     {{{{{hexes(products[0])}}}, {{{hexes(products[1])}}}}},\n"
                     f"     {{{{{hexes(inverses[0])}}}, {{{hexes(inverses[1])}}}}}}},")
    lines.append("};")

    lines.append("// {quaternion, MakeRotationFromKey at single precision, then at double}.")
    lines.append("static const KeyRotationVector kKeyRotationVectors[] = {")
    for k in range(300):
        q = quaternion(rng, unit=k % 4 != 3)
        key = emu.scratch(struct.pack("<i4f", 0, *q))
        results = [oracle.matrix_call(p, ROTATION_FROM_KEY, key) for p in PRECISIONS]
        lines.append(f"    {{{{{hexes(bits(v) for v in q)}}}, {{{{{hexes(results[0])}}}, {{{hexes(results[1])}}}}}}},")
    lines.append("};")

    lines.append("// {key count, frames, values, time, GetMatrixAt at single precision, then at double}.")
    lines.append("static const TrackVector kTranslationTracks[] = {")
    for _ in range(200):
        count = rng.randint(2, 4)
        frames = track_frames(rng, count)
        values = [[f32(rng.uniform(-300, 300)) for _ in range(3)] for _ in range(count)]
        time = rng.choice([rng.randint(frames[0] - 30, frames[-1] - 1), rng.choice(frames[:-1])])
        keys = oracle.track([struct.pack("<i3f", f, *v) for f, v in zip(frames, values)], 16)
        results = []
        for p in PRECISIONS:
            emu.uc.reg_write(UC_X86_REG_FPCW, p)
            emu.call(TRANSLATION_AT, time, oracle.out, this=keys)
            results.append(list(struct.unpack("<12I", emu.mem_read(oracle.out, 48))))
        padded = values + [[0.0] * 3] * (4 - count)
        lines.append(f"    {{{count}, {{{', '.join(map(str, frames + [0] * (4 - count)))}}}, "
                     f"{{{hexes(bits(c) for v in padded for c in v + [0.0])}}}, {time},\n"
                     f"     {{{{{hexes(results[0])}}}, {{{hexes(results[1])}}}}}}},")
    lines.append("};")

    lines.append("static const TrackVector kRotationTracks[] = {")
    for k in range(200):
        count = rng.randint(2, 4)
        frames = track_frames(rng, count)
        values = [quaternion(rng) for _ in range(count)]
        if k % 10 == 0:
            values = [[f32(rng.uniform(-1, 1)), f32(rng.uniform(-1, 1)), f32(rng.uniform(-1, 1)), 1.0]
                      for _ in range(count)]
        elif k % 7 == 0:
            values[1] = [f32(c + rng.uniform(-1e-4, 1e-4)) for c in values[0]]
        time = rng.choice([rng.randint(frames[0] - 30, frames[-1] - 1), rng.choice(frames[:-1])])
        keys = oracle.track([struct.pack("<i4f", f, *v) for f, v in zip(frames, values)], 20)
        results = []
        for p in PRECISIONS:
            emu.uc.reg_write(UC_X86_REG_FPCW, p)
            emu.call(ROTATION_AT, time, oracle.out, this=keys)
            results.append(list(struct.unpack("<12I", emu.mem_read(oracle.out, 48))))
        padded = values + [[0.0] * 4] * (4 - count)
        lines.append(f"    {{{count}, {{{', '.join(map(str, frames + [0] * (4 - count)))}}}, "
                     f"{{{hexes(bits(c) for v in padded for c in v)}}}, {time},\n"
                     f"     {{{{{hexes(results[0])}}}, {{{hexes(results[1])}}}}}}},")
    lines.append("};")
    emu.uc.mem_map(CODE, 0x1000, UC_PROT_ALL)
    stubs = {}
    for k, target in enumerate((SQRT_FLOAT, SIN_FLOAT, COS_FLOAT)):
        # push [esp + 4]; call target; add esp, 4; mov eax, [esp + 8]; fstp dword [eax]; ret
        at = CODE + 0x20 * k
        emu.mem_write(at, b"\xff\x74\x24\x04\xe8" + struct.pack("<i", target - (at + 9))
                      + b"\x83\xc4\x04\x8b\x44\x24\x08\xd9\x18\xc3")
        stubs[target] = at

    def run(target, x):
        emu.uc.reg_write(UC_X86_REG_FPCW, PRECISIONS[0])
        emu.call(stubs[target], x, oracle.out)
        return emu.read_u32(oracle.out)

    randoms = [bits(f32(rng.uniform(-10, 10))) for _ in range(40)]
    lines.append("// {x, SqrtFloat} at single precision.")
    lines.append("static const std::uint32_t kSqrtFloats[][2] = {")
    for x in [0x00000000, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 0xFFC00000, 0x7FC12345,
              0xBF800000, 0xC2C80000, 0x3F800000, 0x4F000000] + randoms:
        lines.append(f"    {{0x{x:08x}, 0x{run(SQRT_FLOAT, x):08x}}},")
    lines.append("};")
    lines.append("// {x, SinFloat, CosFloat} at single precision.")
    lines.append("static const std::uint32_t kTrigFloats[][3] = {")
    for x in [0x00000000, 0x80000000, 0x3F800000, 0xBF800000, 0x40490FDB, 0x3FC90FDB, 0x42C80000] + randoms:
        lines.append(f"    {{0x{x:08x}, 0x{run(SIN_FLOAT, x):08x}, 0x{run(COS_FLOAT, x):08x}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
