"""Test vectors for actors dying (world::KillGameActor, world::KillGameActorAfterQueue, and state 3
of world::SetGameActorState and world::ProcessGameActorState, src/world/actor_state.h), taken from
the original in the emulation oracle.

usage: .venv/bin/python -I tools/death_vectors.py > tests/unit/death_vectors.inc

On tools/walk_vectors.py's three small maps, scripts as tools/walk_oracle.py's make_deaths makes
them (D and H), then on the open field deaths whose results each hang on one thing: each way of
dying from the states that block it or not; the monsters' ids by the job's edges and the ids'
(the mounted jobs among them); something queued, by the job's edge, and +0x210; the frozen body's
ice in its slot or not; the update to the action's end and past it, by the job's edge for the
corpse, with a sprite or none, queued or not; and players, who stay.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle
import path_vectors
import walk_oracle
import walk_vectors


def deciding(script):
    """Deaths made from the first D and H lines of a generated script."""
    d = next(q for q in script if q[0] == "D").split()
    h = next(q for q in script if q[0] == "H").split()
    lines = []

    def die(how=0x1C, state=0, d0=0, job=1100, actor_id=5000, effect=0, body=0, queued=0, f210=0, sprite=1,
            slots=0, updates=40, frames=2, player=False, hold=0, fcc=0):
        tokens = h if player else d
        n = 44 if player else 39
        f = tokens[1:1 + n]
        f[7], f[8], f[10], f[17], f[19], f[34] = (str(job), str(effect), str(frames), str(state), str(d0),
                                                  str(actor_id & 0xFFFFFFFF))
        f[12], f[14] = "0", "0"
        server, tick = int(tokens[1 + n + 9]), int(tokens[1 + n + 10])
        f[11] = str((tick + hold) & 0xFFFFFFFF if hold else 0)
        times = [str(server), str(tick)]
        for k in range(1, updates + 1):
            times += [str((server + 100 * k) & 0xFFFFFFFF), str((tick + 100 * k) & 0xFFFFFFFF)]
        lines.append(("H " if player else "D ") + " ".join(
            f + [str(how), str(body), str(queued), str(f210), str(sprite), str(fcc), str(slots), "0", "0"] + times))

    # Each way of dying, from states that block it (3, +0xd0) or not.
    for how in (0, 0xC, 0x1C):
        for state, d0 in ((0, 0), (2, 0), (3, 0), (4, 0), (5, 0), (8, 0), (10, 0), (12, 0), (0, 1)):
            die(how=how, state=state, d0=d0, updates=2)
    # The monsters' ids by the job's edges (GetJob's: 7 and 14 mounted are 13 and 21), and by the ids'.
    for job, effect in ((1000, 0), (1001, 0), (0x57F, 0), (0x580, 0), (7, 0x20), (14, 0x20), (0x16, 0), (0x17, 0)):
        die(job=job, effect=effect, updates=1)
    for actor_id in (0, 100000, 100001, 99999, 0x7FFFFFFF, -1, -100000):
        die(actor_id=actor_id, updates=1)
    # Something queued, by the job's edge (0x16), and +0x210 before.
    for job in (0x15, 0x16, 0x17, 1100, 7, 14):
        for queued, f210 in ((0, 0), (1, 0), (3, 1), (0, 1)):
            die(job=job, effect=0x20 if job in (7, 14) else 0, queued=queued, f210=f210, updates=3)
    # The frozen body's ice, in its slot or not, and the other body states.
    for body in (0, 1, 2, 3, 4):
        for slots in (0, 1 << 3, 0x7FF):
            die(how=0, body=body, slots=slots, updates=1)
    # The update to the action's end and past it: the corpse by the job's edge, a sprite or none,
    # something queued or not.
    for job in (0x15, 0x16, 0x17, 1100, 50):
        for sprite in (0, 1):
            die(how=0, job=job, sprite=sprite, frames=1)
            die(how=0, job=job, sprite=sprite, frames=3, queued=1)
    die(how=0, job=1100, frames=13)
    # Held (+0x1d0) through the updates, and +0xcc before, which dying's update clears.
    for hold in (150, 1000, 5000):
        die(how=0, job=1100, frames=3, hold=hold, updates=8)
        die(how=0, job=7, frames=3, hold=hold, updates=8, player=True)
    for fcc in (1, 7):
        die(how=0x1C, job=1100, fcc=fcc, updates=3)
        die(how=0x1C, job=7, fcc=fcc, updates=3, player=True)
    # Players, who stay.
    for how in (0, 0xC, 0x1C):
        for state in (0, 2, 3, 8):
            die(how=how, state=state, job=7, frames=1, updates=6, player=True)
    die(how=0x1C, job=7, queued=2, player=True)
    die(how=0, body=2, slots=1 << 3, job=7, player=True)
    return lines


def main():
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/death_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's searches")
    lines.append("// and deaths in order (tools/walk_oracle.py's script and output), then chosen ones.")
    lines.append("static const StateQueryVector kDeathQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_deaths(name, width, height, attrs, 12, updates=(4, 12, 30, 80))
        if name == "open":
            script += deciding(script)
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
