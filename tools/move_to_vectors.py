"""Test vectors for the port's moves from where an actor stands (world::MoveGameActorTo and
world::CellPointAt, src/world/actor_state.h), taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/move_to_vectors.py > tests/unit/move_to_vectors.inc

  - Moves: on tools/walk_vectors.py's three small maps, scripts as tools/walk_oracle.py's make_tos
    makes them (CGameActor::SendMsg's message 0x13 to actors and players, then
    CGameActor::ProcessState update by update with SetState run, to standing), with short walks.
  - CGameMode 00511c30, the cell and sixteenths under a point: points on and either side of
    the cells' and the sixteenths' edges, both sides of 0, beyond the map and beyond 2^31 cells,
    on a map 12 by 10 cells and one 7 by 5.
The x87 runs at single precision, as in the client.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle  # noqa: E402
import path_vectors  # noqa: E402
import state_vectors  # noqa: E402
import walk_oracle  # noqa: E402
import walk_vectors  # noqa: E402

CELL_POINT = 0x511C30


def main():
    rng = random.Random(1907)
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/move_to_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's searches")
    lines.append("// and moves from where the actor stands in order, on one finder and one path")
    lines.append("// (tools/walk_oracle.py's script and output).")
    lines.append("static const StateQueryVector kMoveToQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_tos(name, width, height, attrs, 30, updates=(4, 12, 30, 80))
        for query, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{query}\", \"{result}\"}},")
    lines.append("};")
    lines.append("// CGameMode 00511c30: {width, height, x, z (float bits), the cell, the sixteenths}.")
    lines.append("static const CellPointVector kCellPoints[] = {")
    emu = oracle.emu
    out = emu.scratch(size=16)
    for width, height in ((12, 10), (7, 5)):
        emu.serve_data_files({"data\\t.gat": walk_vectors.gat(["." * width] * height, False)})
        emu.mem_write(oracle.attr, bytes(0x12C))
        emu.call(path_oracle.C3DATTR_CTOR, this=oracle.attr)
        emu.call(path_oracle.C3DATTR_LOAD, emu.cstr("t.gat"), this=oracle.attr)
        points = []
        for edge in (-30.0, -15.0, -5.0, -2.5, -0.3125, 0.0, 0.3125, 2.5, 4.6875, 5.0, 12.5, 25.0, 30.0, 40.0):
            for n in (-1, 0, 1):
                points.append(state_vectors.f32(state_vectors.step(edge, n)))
        points += [state_vectors.f32(rng.uniform(-60, 60)) for _ in range(12)]
        # Beyond 2^31 cells, where the cell wraps through __ftol and the sixteenths go past 16.
        points += [state_vectors.f32(v) for v in (1.5e10, -1.5e10, 2.2e10, 3.7e10, 1e20, -1e20)]
        for x in points:
            z = rng.choice(points)
            emu.call(CELL_POINT, state_vectors.bits(x), state_vectors.bits(z), out, out + 4, out + 8, out + 12,
                     this=oracle.mode)
            cx, cz, sx, sz = struct.unpack("<4i", emu.mem_read(out, 16))
            lines.append(f"    {{{width}, {height}, 0x{state_vectors.bits(x):08x}, "
                         f"0x{state_vectors.bits(z):08x}, {cx}, {cz}, {sx}, {sz}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
