"""Test vectors for the server's moves (world::ServerClock, ReadOwnMove and ReadActorMove,
src/world/server_moves.h), taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/server_move_vectors.py > tests/unit/server_move_vectors.inc

CGameMode::HandlePacket_0087 (00526d60), the own player's move, and HandlePacket_0086
(00526ca0), another actor's, on packets whose cells are each byte's edges and random bytes, at
times about the server clock's ClientState::SyncServerTime (00593170) bounds: 72 ms late and
72 early, both sides, with ClientState's offset (+0x504) and its count of early times (+0x51c)
varied, about 2^32 too. The own player (CWorld+0x3c) and the actor CWorld::GetActorById
(004c4cf0) finds, or not, are stand-ins whose vf02 records its words and the record its first
points at.
"""

import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu.emulator import Emulator
from emu.winapi import Stub
from unicorn import UC_PROT_ALL

HANDLE_0087, HANDLE_0086, GET_ACTOR_BY_ID = 0x526D60, 0x526CA0, 0x4C4CF0
CLIENT_STATE, OFFSET, EARLY = 0x686670, 0x504, 0x51C
STUBS, SEND_SLOT = 0x7E000000, 2
INPUTS = ["kind", "now", "offset", "early", "found", "id", "time"] + [f"cell{k}" for k in range(6)]
# The most words a vector records: the clock, one id asked, one message.
OUTPUTS = 16
# The server clock's lag (ClientState::GetServerTime, 00593200).
LAG = 72


class Oracle:
    def __init__(self):
        emu = self.emu = Emulator().init_crt()
        self.now = 0
        emu.api.stubs["WINMM.DLL!timeGetTime"] = Stub(0, lambda: self.now)
        self.mode, self.world = emu.scratch(size=0x400), emu.scratch(size=0x100)
        emu.write_u32(self.mode + 0xB4, self.world)
        emu.uc.mem_map(STUBS, 0x1000, UC_PROT_ALL)
        emu.mem_write(STUBS, b"\xC3" * 0x10)
        vtable = emu.scratch(size=0x40)
        emu.write_u32(vtable + 4 * SEND_SLOT, STUBS)
        self.actor = emu.scratch(size=0x10)
        emu.write_u32(self.actor, vtable)
        emu.write_u32(self.world + 0x3C, self.actor)
        self.sent = []
        emu.replace_thiscall(STUBS, 5, lambda this, sender, message, a, b, c: self.sent.append(
            [sender, message, *struct.unpack("<7I", emu.mem_read(a, 28)), b, c]))
        self.asked = []
        self.found = False
        emu.replace_thiscall(GET_ACTOR_BY_ID, 1, lambda this, actor_id: self.asked.append(actor_id) or (
            self.actor if self.found else 0))

    def run(self, v):
        emu = self.emu
        self.now = v["now"]
        self.found = bool(v["found"])
        self.sent, self.asked = [], []
        emu.write_u32(CLIENT_STATE + OFFSET, v["offset"])
        emu.write_u32(CLIENT_STATE + EARLY, v["early"])
        cells = bytes(v[f"cell{k}"] for k in range(6))
        if v["kind"] == 0x87:
            packet = struct.pack("<HI", 0x87, v["time"]) + cells
            emu.call(HANDLE_0087, emu.scratch(packet), this=self.mode)
        else:
            packet = struct.pack("<HI", 0x86, v["id"]) + cells + struct.pack("<I", v["time"])
            emu.call(HANDLE_0086, emu.scratch(packet), this=self.mode)
        out = [emu.read_u32(CLIENT_STATE + OFFSET), emu.read_u32(CLIENT_STATE + EARLY), len(self.asked)]
        out += self.asked
        out.append(len(self.sent))
        for s in self.sent:
            out += s
        return out


def vectors():
    rng = random.Random(0x526D60)
    edges = [0x00, 0x01, 0x03, 0x0F, 0x3F, 0x40, 0x80, 0xC0, 0xF0, 0xFC, 0xFF]
    out = []
    for n in range(800):
        now = rng.choice([1000000, 1000000, 0, 71, 72, 73, 0xFFFFFFFF, 0xFFFFFFB8, rng.getrandbits(32)])
        offset = rng.choice([0, 0, 1, 0xFFFFFFFF, 1000, rng.getrandbits(32)])
        server = (now - LAG - offset) & 0xFFFFFFFF
        # The time against the clock's bounds: later than 72 ms ahead resets it, earlier than 72
        # behind counts toward a reset.
        delta = rng.choice([-73, -72, -71, -1, 0, 1, 71, 72, 73, 74, 144, 145, -145, -1000, 1000,
                            rng.randint(-5000, 5000)])
        time = rng.choice([(server + delta) & 0xFFFFFFFF] * 6 + [rng.getrandbits(32)])
        cells = [rng.choice(edges) if n % 3 == 0 else rng.getrandbits(8) for _ in range(6)]
        out.append({
            "kind": 0x87 if n % 2 == 0 else 0x86,
            "now": now,
            "offset": offset,
            "early": rng.choice([0, 0, 1, 2, 3, 3, 4, 5, 0x7FFFFFFF, 0xFFFFFFFF]),
            "found": rng.choice([0, 1, 1]),
            "id": rng.choice([0, 110000, 2000000, rng.getrandbits(32)]),
            "time": time,
            **{f"cell{k}": c for k, c in enumerate(cells)},
        })
    return out


def main():
    o = Oracle()
    lines = [
        "// Generated by tools/server_move_vectors.py from the original in the emulation oracle.",
        "// CGameMode::HandlePacket_0087 (00526d60) and HandlePacket_0086 (00526ca0): {" + ", ".join(INPUTS) + "},",
        "// then ClientState+0x504 and +0x51c after, the ids CWorld::GetActorById was asked for and the",
        "// messages sent (the sender, the message, the record's seven words, the last two words), each",
        "// list after its count.",
        "static const ServerMoveVector kServerMoves[] = {",
    ]
    for v in vectors():
        given = ", ".join(f"0x{v[k] & 0xFFFFFFFF:x}" for k in INPUTS)
        got = o.run(v)
        got += [0] * (OUTPUTS - len(got))
        lines.append(f"    {{{{{given}}},\n     {{{', '.join(f'0x{x:x}' for x in got)}}}}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
