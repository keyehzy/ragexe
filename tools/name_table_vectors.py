"""Test vectors for the port's built-in name tables (docs/formats/client_tables.md#built-in-tables),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/name_table_vectors.py > tests/unit/name_table_vectors.inc

  - ClientState::InitJobAndSkillNames (0058ac70) for service types (0067c9d4) 0 to 8: every one of
    the job names (+0x754), the skill names (+0x410), the guild skill names (+0x490) and the
    sexes' letters (+0x764), and the sizes of the vectors of zeros beside them (+0x450,
    +0x460, +0x4a0).
  - ClientState::InitShadowScales (0059a5e0), then GetShadowScale (0059b750) for every job.
  - CNpc::vf16 (0053fae0) for every job on service type 1, with the actor's own job
    (CGameActor::GetJob, 00503490, stood in for) the same, below 1000 or not: the names it
    gives SetSprite (005018a0) and SetAct (00501910), recorded, and the shadow scale it keeps
    at +0x40. ClientState (00686670) is built by both functions above first.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402

INIT_NAMES, INIT_SHADOWS, GET_SHADOW, SERVICE = 0x58AC70, 0x59A5E0, 0x59B750, 0x67C9D4
NPC_VF16, GET_JOB, SET_SPRITE, SET_ACT, CLIENT_STATE = 0x53FAE0, 0x503490, 0x5018A0, 0x501910, 0x686670
CLIENT_STATE_SIZE = 0x1800


def strings(emu, cs, offset):
    begin = emu.read_u32(cs + offset + 4)
    count = (emu.read_u32(cs + offset + 8) - begin) // 4
    pointers = struct.unpack(f"<{count}I", emu.mem_read(begin, 4 * count))
    return [emu.read_cstr(p, 64, encoding="latin-1") for p in pointers]


def zeros(emu, cs, offset):
    begin = emu.read_u32(cs + offset + 4)
    count = (emu.read_u32(cs + offset + 8) - begin) // 4
    assert not any(struct.unpack(f"<{count}I", emu.mem_read(begin, 4 * count)))
    return count


def c_list(values):
    return ", ".join(f'"{v}"' for v in values)


def main():
    lines = ["// Generated by tools/name_table_vectors.py from the original in the emulation oracle."]
    services = []
    for service in range(9):
        emu = Emulator().init_crt()
        emu.write_u32(SERVICE, service)
        cs = emu.scratch(size=CLIENT_STATE_SIZE)
        emu.call(INIT_NAMES, this=cs)
        jobs = strings(emu, cs, 0x754)
        lines.append(f"static const char* const kJobNames{service}[] = {{{c_list(jobs)}}};")
        services.append(f"    {{{service}, kJobNames{service}, {len(jobs)}}},")
        if service == 0:
            skills = strings(emu, cs, 0x410)
            guild = strings(emu, cs, 0x490)
            sexes = strings(emu, cs, 0x764)
            sizes = [zeros(emu, cs, o) for o in (0x450, 0x460, 0x4A0)]
            emu.call(INIT_SHADOWS, this=cs)
            scales = [struct.unpack("<I", struct.pack("<f", emu.call(GET_SHADOW, job, this=cs).st0))[0]
                      for job in range(0x580)]
    lines.append("// {service type, the job names, their count}.")
    lines.append("static const JobNamesVector kJobNameTables[] = {")
    lines += services
    lines.append("};")
    lines.append(f"static const char* const kSkillNames[] = {{{c_list(skills)}}};")
    lines.append(f"static const char* const kGuildSkillNames[] = {{{c_list(guild)}}};")
    lines.append(f"static const char* const kSexLetters[] = {{{c_list(sexes)}}};")
    lines.append("// The vectors of zeros beside the skill names (+0x450, +0x460) and the guild's (+0x4a0).")
    lines.append(f"static const int kZeroVectorSizes[] = {{{', '.join(map(str, sizes))}}};")
    lines.append("// GetShadowScale for each job, as bits.")
    lines.append("static const unsigned kShadowScales[] = {" + ", ".join(f"0x{s:08x}" for s in scales) + "};")
    lines += npc_sprites()
    print("\n".join(lines))


def npc_sprites():
    emu = Emulator().init_crt()
    emu.write_u32(SERVICE, 1)
    emu.call(INIT_NAMES, this=CLIENT_STATE)
    emu.call(INIT_SHADOWS, this=CLIENT_STATE)
    state = {}
    emu.replace_thiscall(GET_JOB, 0, lambda this: state["actor_job"] & 0xFFFFFFFF)
    emu.replace_thiscall(SET_SPRITE, 1, lambda this, name: state.__setitem__("sprite", emu.read_cstr(
        name, 128, encoding="latin-1")) or 0)
    emu.replace_thiscall(SET_ACT, 1, lambda this, name: state.__setitem__("act", emu.read_cstr(
        name, 128, encoding="latin-1")) or 0)
    npc = emu.scratch(size=0x400)
    rows = []
    for job in range(0x580):
        for actor_job in sorted({job, job % 1000, 1000 + job % 408, -1 - job % 7}):
            state.update(actor_job=actor_job, sprite=None, act=None)
            emu.call(NPC_VF16, job, this=npc)
            scale = emu.read_u32(npc + 0x40)
            sprite = state["sprite"].encode("latin-1")
            act = state["act"].encode("latin-1")
            rows.append(f'    {{{job}, {actor_job}, "{c_bytes(sprite)}", "{c_bytes(act)}", 0x{scale:08x}}},')
    return ["// CNpc::vf16 on service type 1: {job, the actor's own job, the sprite and actions it sets,",
            "// the shadow scale it keeps}.",
            "static const NpcSpriteVector kNpcSprites[] = {"] + rows + ["};"]


def c_bytes(data):
    return "".join(f"\\{c:03o}" if c >= 0x80 or c in (0x22, 0x5C) else chr(c) for c in data)


if __name__ == "__main__":
    main()
