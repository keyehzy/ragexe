"""Test vectors for an NPC's drawing (world::DrawNpc, src/world/actor_draw.h), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/npc_draw_vectors.py > tests/unit/npc_draw_vectors.inc

CNpc::Render (00540610) on CNpc objects (vtable 005e991c) of assorted jobs (the table's edges,
the mounted 7 and 14, players, NPCs, monsters), shown or not (+0x84, +0x85), opaque or not
(+0x7c), with assorted scales, +0x1ec and +0x1f0 (odd, negative, past 2^24, and halves a float cannot hold), effects on or off
(00687ea8), at positions about the views tools/actor_vectors.py builds (some far, some behind
the camera), on projections of assorted sizes (SceneRenderer::SetSize, 0040db70). The four
calls it makes are recorded in order and skipped: DrawShadow (00501550) with its scale, DrawBody
(00500f70), ProjectToScreen (00500ed0), and vf05 (CGameActor::OnScreenBounds, 00502cc0) with the
bounds, the 1/z and the point; then +0x48.
The x87 runs at single precision, as in the client.
"""

import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from actor_vectors import (
    DRAW_BODY,
    DRAW_SHADOW,
    PROJECT_TO_SCREEN,
    SCALES,
    SET_SIZE,
    UNSET,
    Oracle,
    bits,
    f32,
    hexs,
)

NPC_RENDER, NPC_VTABLE, ON_SCREEN_BOUNDS = 0x540610, 0x5E991C, 0x502CC0
EFFECTS_ON = 0x687EA8
NPC_SIZE = 0x300
SIZES = [(640, 480), (800, 600), (1024, 768), (1280, 1024), (801, 601)]
VIEWS = [
    (-45.0, 0.0, 300.0),
    (-45.0, 90.0, 230.0),
    (-30.0, 200.0, 400.0),
    (-60.5, 45.0, 260.0),
    (-89.0, 10.0, 300.0),
    (-20.4, 135.0, 250.0),
]
JOBS = [
    0,
    1,
    7,
    13,
    14,
    21,
    44,
    45,
    46,
    103,
    104,
    105,
    110,
    111,
    112,
    138,
    139,
    140,
    999,
    1000,
    1002,
    -1,
    0x7FFFFFFF,
]
HALVES = [
    0,
    1,
    2,
    3,
    7,
    40,
    41,
    100,
    255,
    -1,
    -2,
    -5,
    -40,
    0x1000001,
    0x1000003,
    0x2345679,
    0x7FFFFFFF,
    -0x80000000,
    -0x1000003,
]
# Halves a float cannot hold (odd, past 2^24), where fild's exact value and the float differ.
WIDE = [
    0x2000002,
    0x2000006,
    0x68ACF12,
    0x7654321,
    0x3FFFFFF,
    -0x2000002,
    -0x68ACF13,
    0x5555555,
]


def main():
    rng = random.Random(45)
    o = Oracle()
    emu = o.emu
    calls = []

    def recorder(kind):
        def fn(this, *args):
            calls.append((kind, args))
            return 0

        return fn

    emu.replace_thiscall(DRAW_SHADOW, 2, recorder(1))
    emu.replace_thiscall(DRAW_BODY, 1, recorder(2))
    emu.replace_thiscall(PROJECT_TO_SCREEN, 1, recorder(3))
    emu.replace_thiscall(ON_SCREEN_BOUNDS, 3, recorder(5))
    npc = emu.scratch(size=NPC_SIZE)
    lines = [
        "// Generated by tools/npc_draw_vectors.py from the original in the emulation oracle.",
        "// CNpc::Render (00540610): {projection width, height, the view, 0061470c, position, job,",
        "// +0x21c, +0x3c, +0x7c, +0x84, +0x85, +0x1ec, +0x1f0, effects on}, then the calls in",
        "// order (1 DrawShadow and its scale, 2 DrawBody, 3 ProjectToScreen, 5 vf05 and the",
        "// bounds, 1/z, x and y), their words' count, and +0x48 after (0x11111111 untouched).",
    ]
    lines.append("static const NpcDrawVector kNpcDraws[] = {")
    views = {}
    for k in range(420):
        w, h = SIZES[k % len(SIZES)]
        emu.call(SET_SIZE, w, h, this=o.renderer)
        v = (k // len(SIZES)) % len(VIEWS)
        if (w, h, v) not in views:
            at = (rng.uniform(-50, 50), rng.uniform(-20, 0), rng.uniform(-50, 50))
            views[(w, h, v)] = (*o.build_view(*map(f32, VIEWS[v]), at), at)
        view, scales, at = views[(w, h, v)]
        for key, value in zip(SCALES, scales):
            emu.write_u32(SCALES[key], value)
        spread = rng.choice([1, 1, 1, 8, 40])
        pos = tuple(
            f32(c)
            for c in (
                at[0] + rng.uniform(-60, 60) * spread,
                rng.uniform(-25, 5),
                at[2] + rng.uniform(-60, 60) * spread,
            )
        )
        job = rng.choice(JOBS + [45, 45, 111, 111, 104, 139, rng.randrange(45, 140)])
        effect_state = rng.choice([0, 0, 0x20, 0x10, 0x30, rng.getrandbits(32)])
        scale = f32(rng.choice([1.0, 1.0, 0.5, 1.5, 0.0, 2.0, 0.75]))
        color = rng.choice(
            [
                0xFFFFFFFF,
                0xFFFFFFFF,
                0x80FFFFFF,
                0xFE102030,
                0x00FFFFFF,
                rng.getrandbits(32),
            ]
        )
        visible, body_shown = int(rng.random() < 0.8), int(rng.random() < 0.75)
        wide = rng.random() < 0.15
        half_w = rng.choice(WIDE if wide else HALVES + [rng.randrange(-300, 300)])
        half_h = rng.choice(WIDE if wide else HALVES + [rng.randrange(300)])
        if wide:
            job = 111
        effects_on = int(rng.random() < 0.5)
        emu.mem_write(npc, bytes(NPC_SIZE))
        emu.write_u32(npc, NPC_VTABLE)
        emu.mem_write(npc + 4, struct.pack("<3f", *pos))
        emu.mem_write(npc + 0x3C, struct.pack("<2f", scale, 1.0))
        emu.write_u32(npc + 0x48, UNSET)
        emu.write_u32(npc + 0x7C, color)
        emu.mem_write(npc + 0x84, bytes([visible, body_shown]))
        emu.write_u32(npc + 0x1B8, job & 0xFFFFFFFF)
        emu.write_u32(npc + 0x1EC, half_w & 0xFFFFFFFF)
        emu.write_u32(npc + 0x1F0, half_h & 0xFFFFFFFF)
        emu.write_u32(npc + 0x21C, effect_state)
        emu.write_u32(EFFECTS_ON, effects_on)
        matrix = emu.scratch(struct.pack("<12I", *view))
        del calls[:]
        emu.call(NPC_RENDER, matrix, this=npc)
        words = []
        for kind, args in calls:
            if kind == 5:
                words += [
                    5,
                    *struct.unpack("<5I", emu.mem_read(args[0], 20)),
                    args[1],
                    args[2],
                ]
            else:
                assert args[0] == matrix
                words += [kind, *args[1:]]
        lines.append(
            f"    {{{w}, {h}, {{{hexs(view)}}}, 0x{scales[0]:08x}, {{{hexs(map(bits, pos))}}}, {job}, "
            f"0x{effect_state:08x}, 0x{bits(scale):08x}, 0x{color:08x}, {visible}, {body_shown}, "
            f"{half_w}, {half_h}, {effects_on}, {{{hexs(words)}}}, {len(words)}, "
            f"0x{emu.read_u32(npc + 0x48):08x}}},"
        )
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
