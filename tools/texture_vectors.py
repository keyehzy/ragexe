"""Test vectors for the port's texture and surface uploads (docs/render/texture.md),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/texture_vectors.py > tests/unit/texture_vectors.inc

  - CTexture::UpdatePixels (00416990) into an 8 x 8 texture of each pixel format, with
    and without black as transparent, from images that fit, need sampling down, sit at
    an offset or have a wider stride: every texel afterwards, and the image's uv scale.
  - CTexture::DrawRleImage (00416d80): run-length sprite images through a palette into
    a 16 x 8 texture, including a zero-length run and areas larger than the image.
  - CSurface::UpdatePixels (00416130) into 16- and 32-bit surfaces, with the device's
    channels for 565, 555 and X888.
  - CTexture::FillColor (00416750): the fill value Blt receives for a colour.
Texture memory starts filled with 0xa5 bytes, so texels the original leaves alone show.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402
from emu.directx import DDSCAPS_TEXTURE, PF_565, PF_555, PF_1555, PF_4444, PF_8888, PF_X888, Surface  # noqa: E402

TEXTURE_UPDATE, DRAW_RLE, SURFACE_UPDATE, FILL_COLOR = 0x416990, 0x416D80, 0x416130, 0x416750
G_C3DDEVICE = 0x6239D0
FORMATS = {0: PF_1555, 1: PF_4444, 2: PF_565, 4: PF_8888}
SPECIAL = [0, 0xFFFF00FF, 0x00FF00FF, 0x80FF00FF, 0x7FFF00FF, 0xFF000000, 0x80000000, 0x00FFFFFF,
           0xFFFFFFFF, 0x7FFFFFFF, 0xFF00FF00, 0xFFF80000, 0x8007E01F, 0x0F0F0F0F, 0xFF808080, 0x00000001]
# (width, height, x, y, stride)
SHAPES = [(8, 8, 0, 0, 0), (16, 8, 0, 0, 0), (20, 13, 0, 0, 0), (5, 3, 2, 1, 0), (6, 4, 0, 2, 9)]
# The device's channel fields (+0x1f0: shift and loss for red, green, blue, alpha) by format.
CHANNELS = {"565": (11, 3, 5, 2, 0, 3, 0, 8), "555": (10, 3, 5, 3, 0, 3, 0, 8),
            "x888": (16, 0, 8, 0, 0, 0, 0, 8)}


def source(rng, w, h, stride):
    return [rng.choice(SPECIAL) if rng.random() < 0.5 else rng.getrandbits(32)
            for _ in range(max(stride, w) * h)]


def array(name, values):
    out = [f"static const std::uint32_t {name}[] = {{"]
    for k in range(0, len(values), 8):
        out.append("    " + ", ".join(f"0x{v:x}" for v in values[k:k + 8]) + ",")
    out.append("};")
    return out


def surface_values(surface, width, height):
    bits = struct.unpack_from("<I", surface.pf, 12)[0]
    data = surface.pixels()
    fmt = "<H" if bits == 16 else "<I"
    step = bits // 8
    return [struct.unpack_from(fmt, data, y * surface.pitch + x * step)[0]
            for y in range(height) for x in range(width)]


def fresh_surface(emu, width, height, pf, caps=DDSCAPS_TEXTURE):
    s = Surface(emu.directx, width, height, pf, caps, "texture")
    emu.mem_write(s.memory, b"\xa5" * (s.pitch * height))
    return s


def main():
    rng = random.Random(4)
    emu = Emulator()
    lines = ["// Generated by tools/texture_vectors.py from the original in the emulation oracle."]
    sources = [source(rng, w, h, stride) for w, h, _, _, stride in SHAPES]
    for k, values in enumerate(sources):
        lines += array(f"kSource{k}", values)

    cases = []
    for fmt, pf in FORMATS.items():
        for flag in (0, 1):
            for k, (w, h, x, y, stride) in enumerate(SHAPES):
                surface = fresh_surface(emu, 8, 8, pf)
                tex = emu.scratch(size=0x128)
                for off, v in ((4, 8), (8, 8), (0xC, surface.address), (0x10, fmt)):
                    emu.write_u32(tex + off, v)
                pixels = emu.scratch(struct.pack(f"<{len(sources[k])}I", *sources[k]))
                emu.call(TEXTURE_UPDATE, x, y, w, h, pixels, flag, stride, this=tex)
                u, v = struct.unpack("<II", emu.mem_read(tex + 0x18, 8))
                name = f"kTexels{len(cases)}"
                lines += array(name, surface_values(surface, 8, 8))
                cases.append(f"    {{{fmt}, {flag}, {x}, {y}, {w}, {h}, {stride}, kSource{k}, "
                             f"std::size(kSource{k}), 0x{u:08x}, 0x{v:08x}, {name}}},")
    lines.append("// {format, black transparent, x, y, width, height, stride, source, source size,")
    lines.append("// u scale bits, v scale bits, the 8 x 8 texels afterwards}: 00416990.")
    lines.append("static const UpdateVector kUpdateVectors[] = {")
    lines += cases
    lines.append("};")

    palette = [rng.getrandbits(32) for _ in range(256)]
    lines += array("kRlePalette", palette)
    images = [
        (5, 3, bytes([1, 2, 0, 2, 3, 4, 5, 0, 3, 6, 7, 8, 9, 10])),
        (4, 2, bytes([0, 6, 9, 9])),                     # a run across the row's end
        (3, 3, bytes([7, 0, 0, 1])),                     # a zero-length run: zeros to the end
        (6, 2, bytes(range(1, 13))),
    ]
    rle_cases = []
    for k, (iw, ih, data) in enumerate(images):
        for area in ((iw, ih, 0, 0), (iw + 3, ih + 2, 2, 1)):
            aw, ah, ax, ay = area
            surface = fresh_surface(emu, 16, 8, PF_565)
            tex = emu.scratch(size=0x128)
            for off, v in ((4, 16), (8, 8), (0xC, surface.address), (0x10, 2)):
                emu.write_u32(tex + off, v)
            rle = emu.scratch(data + bytes(16))
            image = emu.scratch(struct.pack("<hh8xI", iw, ih, rle))
            pal = emu.scratch(struct.pack("<256I", *palette))
            emu.call(DRAW_RLE, ax, ay, aw, ah, image, pal, this=tex)
            name = f"kRleTexels{len(rle_cases)}"
            lines += array(name, surface_values(surface, 16, 8))
            lines.append(f"static const std::uint8_t kRleData{len(rle_cases)}[] = {{"
                         + ", ".join(str(b) for b in data) + "};")
            rle_cases.append(f"    {{{ax}, {ay}, {aw}, {ah}, {iw}, {ih}, kRleData{len(rle_cases)}, "
                             f"std::size(kRleData{len(rle_cases)}), {name}}},")
    lines.append("// {x, y, width, height, image width, image height, run-length data, its size,")
    lines.append("// the 16 x 8 texels afterwards}: 00416d80 with kRlePalette.")
    lines.append("static const RleVector kRleVectors[] = {")
    lines += rle_cases
    lines.append("};")

    surface_cases, fill_cases = [], []
    for name, channels in CHANNELS.items():
        for k, value in enumerate(channels):
            emu.write_u32(G_C3DDEVICE + 0x1F0 + 4 * k, value)
        pf = {"565": PF_565, "555": PF_555, "x888": PF_X888}[name]
        for k, (w, h, x, y, stride) in enumerate(SHAPES):
            if x + w > 8 or y + h > 8:
                continue
            surface = fresh_surface(emu, 8, 8, pf, 0x40)
            obj = emu.scratch(size=0x10)
            emu.write_u32(obj + 0xC, surface.address)
            pixels = emu.scratch(struct.pack(f"<{len(sources[k])}I", *sources[k]))
            emu.call(SURFACE_UPDATE, x, y, w, h, pixels, 0, stride, this=obj)
            arr = f"kSurface{len(surface_cases)}"
            lines += array(arr, surface_values(surface, 8, 8))
            surface_cases.append(f'    {{"{name}", {x}, {y}, {w}, {h}, {stride}, kSource{k}, '
                                 f'std::size(kSource{k}), {arr}}},')
        tex = emu.scratch(size=0x128)
        emu.write_u32(tex + 0xC, fresh_surface(emu, 8, 8, PF_565).address)
        for color in (0, 0xFFFFFF, 0x0000FF, 0x00FF00, 0xFF0000, 0x123456, 0xFF00FF, 0x808080):
            emu.call(FILL_COLOR, 0, color, this=tex)
            fill = next(c for c in reversed(emu.directx.calls) if c.method == "Blt").detail["fill"]
            fill_cases.append(f'    {{"{name}", 0x{color:x}, 0x{fill:x}}},')
    lines.append("// {device format, x, y, width, height, stride, source, source size, the 8 x 8")
    lines.append("// pixels afterwards}: 00416130.")
    lines.append("static const SurfaceVector kSurfaceVectors[] = {")
    lines += surface_cases
    lines.append("};")
    lines.append("// {device format, colour, fill value}: 00416750.")
    lines.append("static const FillVector kFillVectors[] = {")
    lines += fill_cases
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
