"""Test vectors for the world's lists (world::WorldObjects, ShowGroundItem and RemoveGroundItem,
src/world/world_objects.h: CWorld's lists and the item packets), taken from the original in the
emulation oracle.

usage: .venv/bin/python -I tools/list_vectors.py > tests/unit/list_vectors.inc

On tools/walk_vectors.py's three small maps, scripts as tools/walk_oracle.py's make_lists makes
them (l), then on the open field scripts that each hang on one thing: actors of one id, found and
deleted first to last; an update that lets go objects among others, in order; an item sent again
by either packet, and after packet 0x00a1 made anew; the ids asked to be picked up, one twice and
one never seen; the player made twice and not among the actors; clearing and starting again; the
packets' words at their edges.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import path_oracle
import path_vectors
import walk_oracle
import walk_vectors

NOW = 100000


def stand_in(kind, actor_id, lives):
    return [0, kind, actor_id, lives]


def item(dropped, item_id, number=501, cell=(5, 4), sub=(8, 8), count=1, identified=1, now=NOW):
    return [1, dropped, item_id, number, identified, cell[0], cell[1], sub[0], sub[1], count, now]


def query(*ops):
    return "l " + " ".join([t.hex() for t in walk_oracle.LIST_TABLES] + [str(w & 0xFFFFFFFF) for op in ops for w in op])


def deciding():
    return [
        # Actors of one id: the first found and deleted, then the next.
        query(stand_in(1, 7, 9), stand_in(1, 7, 9), stand_in(1, 8, 9), [5, 7], [4, 7], [5, 7], [4, 7], [5, 7],
              [4, 7], [5, 8]),
        # An update lets go the objects whose updates return 0, among the others, in order.
        query(stand_in(1, 1, 0), stand_in(0, 0, 1), stand_in(1, 2, 3), stand_in(0, 0, 0), stand_in(1, 3, 1),
              [7, NOW], [7, NOW + 24], [5, 2], [5, 3], [7, NOW + 48], [7, NOW + 72], [5, 2]),
        # An item sent again by either packet, then gone and made anew; dropped, then lying.
        query(item(1, 100), [7, NOW + 120], item(0, 100, 909, (6, 6), (3, 12), 4, 0, NOW + 200), [6, 100],
              [7, NOW + 400], item(1, 100, now=NOW + 500), [2, 100], [6, 100], item(0, 100, now=NOW + 600),
              [6, 100], [7, NOW + 2000]),
        # Items of other ids among actors: each list holds its own, the list all in order.
        query(item(0, 101), stand_in(1, 101, 5), item(1, 102), stand_in(0, 0, 5), [5, 101], [6, 101], [6, 102],
              [4, 101], [6, 101], [2, 101], [5, 101], [2, 102], [2, 103]),
        # The ids asked to be picked up: one twice, one never an item; 0x00a1 takes the first.
        query([3, 100], [3, 100], [3, 555], item(0, 100), [2, 100], [2, 100], [2, 555], [2, 555], [3, 101]),
        # The player made twice: both in the list, the second at +0x3c, neither among the actors.
        query(stand_in(2, 5, 1000000), stand_in(1, 5, 9), stand_in(2, 5, 1000000), [5, 5], [4, 5], [4, 5],
              [7, NOW], [8]),
        # Clearing, then starting again.
        query(stand_in(1, 1, 9), item(0, 100), [3, 100], stand_in(2, 0, 1000000), [8], [5, 1], [6, 100],
              stand_in(1, 1, 9), item(1, 100), [5, 1], [6, 100], [7, NOW + 240], [8], [8]),
        # The packets' words at their edges: the item's number unsigned, counts and cells signed,
        # sixteenths unsigned bytes, identified a byte.
        query(item(0, 100, 65535, (5, 4), (255, 0), -1, 255), item(1, 101, 0, (-3, 99), (15, 16), 65535, 2),
              item(0, 102, 32768, (32767, -32768), (0, 255), 32767, 0), item(1, -7, 1, (5, 4), (8, 8), 0, 1),
              item(0, 0x7FFFFFFF, 501, (0, 0), (0, 0), 1, 1), [6, -7], [6, 0x7FFFFFFF], [7, NOW + 500]),
    ]


def main():
    oracle = path_oracle.Oracle()
    maps = [("open", dict(path_vectors.MAPS)["open"], False), ("walls", dict(path_vectors.MAPS)["walls"], False),
            ("hills", walk_vectors.HILLS, True)]
    lines = ["// Generated by tools/list_vectors.py from the original in the emulation oracle."]
    lines.append("// The maps are tools/walk_vectors.py's (walk_vectors.inc's kWalkMaps). Each map's scripts of")
    lines.append("// the world's lists (tools/walk_oracle.py's), then on map 0 chosen ones.")
    lines.append("static const StateQueryVector kListQueries[] = {")
    for m, (name, rows, hilly) in enumerate(maps):
        width, height = len(rows[0]), len(rows)
        attrs = [path_vectors.ATTRIBUTES[c] for row in rows for c in row]
        script = walk_oracle.make_lists(name, width, height, attrs, 20)
        if name == "open":
            script += deciding()
        for line, result in zip(script, oracle.run(walk_vectors.gat(rows, hilly), script)):
            lines.append(f"    {{{m}, \"{line}\", \"{result}\"}},")
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
