"""Test vectors for a player's drawing (world::DrawPc, src/world/actor_draw.h), taken from the
original in the emulation oracle.

usage: .venv/bin/python -I tools/pc_draw_vectors.py > tests/unit/pc_draw_vectors.inc

CPc::Render (00544380) on CPc objects (vtable 005e9b94), shown or not (+0x84, +0x85), in each
state from -1 to 10 (+0x58), at assorted scales (+0x3c) and colours (+0x7c), with ids about
the Korean service's special ones (+0x1b4) under service types 0, 1 and 2 (0067c9d4). The five
calls it can make are recorded in order and skipped: DrawShadow (00501550) with its scale, 00545540,
DrawBody (00500f70), RenderActFrameItems (00544be0) and ProjectToScreen (00500ed0).
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from actor_vectors import DRAW_BODY, DRAW_SHADOW, PROJECT_TO_SCREEN, Oracle, bits, f32, hexs

PC_RENDER, PC_VTABLE, PC_SIZE = 0x544380, 0x5E9B94, 0x308
SPECIAL_DRAW, RENDER_LAYERS = 0x545540, 0x544BE0
SERVICE_TYPE = 0x67C9D4
STATES = range(-1, 11)
IDS = [0, 0x2C8C7C, 0x2C8C7D, 0x2C8C80, 0x2C8C81, 0x2C8C82, 0x2C8C83, 2000001]
SERVICES = [0, 1, 2]
SCALES = [1.0, 0.5, 0.0, 1.75]
COLORS = [0xFFFFFFFF, 0x80FFFFFF, 0x00FFFFFF, 0xFE102030, 0x7F000000]


def main():
    o = Oracle()
    emu = o.emu
    calls = []

    def recorder(kind):
        def fn(this, *args):
            calls.append((kind, args))
            return 0

        return fn

    emu.replace_thiscall(DRAW_SHADOW, 2, recorder(1))
    emu.replace_thiscall(SPECIAL_DRAW, 2, recorder(2))
    emu.replace_thiscall(DRAW_BODY, 1, recorder(3))
    emu.replace_thiscall(RENDER_LAYERS, 2, recorder(4))
    emu.replace_thiscall(PROJECT_TO_SCREEN, 1, recorder(5))
    pc = emu.scratch(size=PC_SIZE)
    view = emu.scratch(size=0x30)
    lines = [
        "// Generated by tools/pc_draw_vectors.py from the original in the emulation oracle.",
        "// CPc::Render (00544380): {+0x84, +0x85, +0x58, +0x3c, +0x7c, +0x1b4, the service type}, then",
        "// the calls in order (1 DrawShadow and its scale, 2 00545540, 3 DrawBody,",
        "// 4 RenderActFrameItems, 5 ProjectToScreen) and their words' count.",
        "static const PcDrawVector kPcDraws[] = {",
    ]
    k = 0
    for visible in (0, 1):
        for body_shown in (0, 1):
            for state in STATES:
                for actor_id in IDS:
                    for service in SERVICES:
                        scale = f32(SCALES[k % len(SCALES)])
                        color = COLORS[k % len(COLORS)]
                        k += 1
                        emu.mem_write(pc, bytes(PC_SIZE))
                        emu.write_u32(pc, PC_VTABLE)
                        emu.mem_write(pc + 0x3C, struct.pack("<2f", scale, 1.0))
                        emu.write_u32(pc + 0x58, state & 0xFFFFFFFF)
                        emu.write_u32(pc + 0x7C, color)
                        emu.mem_write(pc + 0x84, bytes([visible, body_shown]))
                        emu.write_u32(pc + 0x1B4, actor_id)
                        emu.write_u32(SERVICE_TYPE, service)
                        del calls[:]
                        emu.call(PC_RENDER, view, this=pc)
                        words = []
                        for kind, args in calls:
                            assert args[0] == view
                            if kind == 1:
                                words += [kind, args[1]]
                            else:
                                assert kind == 5 or args[1:] in ((), (0,))
                                words.append(kind)
                        lines.append(
                            f"    {{{visible}, {body_shown}, {state}, 0x{bits(scale):08x}, 0x{color:08x}, 0x{actor_id:x}, {service}, "
                            f"{{{hexs(words)}}}, {len(words)}}},"
                        )
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
