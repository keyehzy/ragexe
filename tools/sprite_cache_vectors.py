"""Test vectors for the sprite texture cache (render::SpriteTextureCache, src/render/sprite_cache.h),
taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/sprite_cache_vectors.py > tests/unit/sprite_cache_vectors.inc

Scripts of frames on one SceneRenderer, its 16 page lists (+0x194) made by their constructor
(0040d800), each frame at a time timeGetTime answers:
  - draws, as SceneRenderer::AddSpriteQuad (0040e980) asks for an 8-bit image: FindCachedSprite
    (0040e540), then CacheSpriteImage (0040e130) when it answers no texture;
  - CacheSpriteImage alone, an image already cached or not;
  - CGameMode's release every 15 s (0050d3d0, its next time at 00685ee0), which runs
    ReleaseExpiredPooledTextures (0040e030).
The images are records whose width and height (+0, +2) cover each size class's edges, some 0
and some negative; the palettes are assorted values. The times start about the edges
timeGetTime - 3750 and - 15000 cross (and near 2^32), and step by a few milliseconds, by
seconds, or past 15. CTexture's constructor (004165e0), its FillColor (vf02, 00416750), its
deleting destructor (00416680) and DrawRleImage (00416d80) are stood in for and recorded: the
pages are numbered in the order made. The x87 runs at single precision, as in the client.
"""

import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unicorn.x86_const import UC_X86_REG_FPCW

from emu import Emulator
from emu.winapi import Stub

FIND_CACHED, CACHE_IMAGE, RELEASE_DUE = 0x40E540, 0x40E130, 0x50D3D0
LIST_CONSTRUCTOR, NEXT_RELEASE, G_PSCENE_RENDERER = 0x40D800, 0x685EE0, 0x625E98
TEXTURE_CONSTRUCTOR, FILL_COLOR, DELETING_DESTRUCTOR, DRAW_RLE = (
    0x4165E0,
    0x416750,
    0x416680,
    0x416D80,
)
TEXTURE_VTABLE = 0x5E270C
SCENE_RENDERER_SIZE = 0x2A0
# The renderer's endless loop: CacheSpriteImage makes pages without end when timeGetTime is
# exactly a quarter of 00612710 (15000), since no slot's time is below 0.
HANG = 3750
SIDES = [
    0,
    1,
    2,
    17,
    31,
    32,
    33,
    50,
    63,
    64,
    65,
    100,
    127,
    128,
    129,
    200,
    255,
    256,
    300,
    -1,
    -40,
    -32768,
    32767,
]
STARTS = [
    0,
    1,
    100,
    3000,
    3749,
    3751,
    3760,
    9000,
    14999,
    15000,
    15001,
    20000,
    1000000,
    0xFFFFFFFF - 2000,
    0xFFFFFFFF - 16000,
]


def hexs(values):
    return ", ".join(f"0x{v:x}" for v in values)


def main():
    rng = random.Random(0x40E130)
    emu = Emulator().init_crt()
    emu.uc.reg_write(UC_X86_REG_FPCW, 0x007F)
    state = {"now": 0}
    emu.api.stubs["WINMM.DLL!timeGetTime"] = Stub(0, lambda: state["now"])
    pages, events, made_count = {}, [], [0]

    def construct(this, width, height, alpha):
        assert (width, height, alpha) == (256, 256, 0)
        made_count[0] += 1
        pages[this] = made_count[0]
        emu.write_u32(this, TEXTURE_VTABLE)
        emu.write_u32(this + 0x120, 0)
        events.append(("new", pages[this]))
        return this

    def fill(this, rect, color):
        assert (rect, color) == (0, 0)
        events.append(("fill", pages[this]))
        return 0

    def delete(this, flags):
        events.append(("delete", pages[this]))
        return this

    def draw(this, x, y, width, height, image, palette):
        events.append(("draw", pages[this], x, y, width, height, image, palette))
        return 1

    emu.replace_thiscall(TEXTURE_CONSTRUCTOR, 3, construct)
    emu.replace_thiscall(FILL_COLOR, 2, fill)
    emu.replace_thiscall(DELETING_DESTRUCTOR, 1, delete)
    emu.replace_thiscall(DRAW_RLE, 6, draw)

    lines = [
        "// Generated by tools/sprite_cache_vectors.py from the original in the emulation oracle.",
        "// The sprite texture cache: the images {width, height}, each script's next release",
        "// (00685ee0) to start, then the ops {script, kind (0 FindCachedSprite then",
        "// CacheSpriteImage on a miss, 1 CacheSpriteImage alone, 2 CGameMode 0050d3d0), image,",
        "// palette, timeGetTime}, then what they did as words:",
        "// FindCachedSprite's page (0 for none) and on a hit u0, v0, u1, v1; CacheSpriteImage's",
        "// page made (or 0), the page, the slot x, y, width, height drawn and u0, v0, u1, v1; the",
        "// release's next time (00685ee0) and the pages it let go, then 0. Pages count from 1 in",
        "// the order made, across the scripts.",
    ]
    images_rows, script_rows, op_rows = [], [], []
    for script in range(32):
        mark = emu.heap_mark()
        renderer = emu.scratch(size=SCENE_RENDERER_SIZE)
        for k in range(16):
            emu.call(LIST_CONSTRUCTOR, this=renderer + 0x194 + 12 * k)
        emu.call(LIST_CONSTRUCTOR, this=renderer + 0x254)
        emu.write_u32(G_PSCENE_RENDERER, renderer)
        emu.write_u32(NEXT_RELEASE, rng.choice([0, 0, 5000, 0xFFFFFFFF]))
        next_release = emu.read_u32(NEXT_RELEASE)
        # Images of a few size classes, so that pages fill and slots are taken back.
        sides = rng.sample(SIDES, rng.randrange(2, 6))
        count = rng.choice([3, 10, 40, 80, 150])
        sizes = [(rng.choice(sides), rng.choice(sides)) for _ in range(count)]
        first = len(images_rows)
        records = [emu.scratch(struct.pack("<2h", w, h), size=16) for w, h in sizes]
        images_rows += [f"{{{w}, {h}}}" for w, h in sizes]
        palettes = [rng.getrandbits(32) for _ in range(rng.choice([1, 1, 2, 3]))]
        now = rng.choice(STARTS)
        script_rows.append(f"0x{next_release:08x}")
        for _ in range(rng.choice([20, 40, 80])):
            for _ in range(rng.choice([1, 3, 8, 20])):
                if now == HANG:
                    now += 1
                state["now"] = now
                roll = rng.random()
                image = rng.randrange(count)
                palette = rng.randrange(len(palettes))
                kind = 2 if roll < 0.04 else 1 if roll < 0.12 else 0
                # Some releases just at their time, which is not yet past it.
                due = emu.read_u32(NEXT_RELEASE)
                if (
                    kind == 2
                    and rng.random() < 0.3
                    and 0 < (due - now) & 0xFFFFFFFF < 40000
                    and due != HANG
                ):
                    now = state["now"] = due
                out = emu.scratch(size=0x1C)
                emu.mem_write(out + 0xC, struct.pack("<4I", *[0x11111111] * 4))
                args = (records[image], palettes[palette], out)
                del events[:]
                words = []
                if kind == 2:
                    emu.call(RELEASE_DUE, this=0)
                    words = [emu.read_u32(NEXT_RELEASE)]
                    words += [e[1] for e in events if e[0] == "delete"]
                    assert all(e[0] == "delete" for e in events)
                    words.append(0)
                else:
                    if kind == 0:
                        found = emu.call(FIND_CACHED, *args, this=renderer).eax
                        words.append(pages.get(found, 0))
                        assert found == 0 or found in pages
                        if found:
                            words += struct.unpack("<4I", emu.mem_read(out + 0xC, 16))
                    if kind == 1 or not found:
                        texture = emu.call(CACHE_IMAGE, *args, this=renderer).eax
                        made = [e[1] for e in events if e[0] == "new"]
                        assert [e[0] for e in events] == (
                            ["new", "fill", "draw"] if made else ["draw"]
                        )
                        drawn = events[-1]
                        assert drawn[1] == pages[texture] and drawn[6:] == args[:2]
                        words += [made[0] if made else 0, pages[texture], *drawn[2:6]]
                        words += struct.unpack("<4I", emu.mem_read(out + 0xC, 16))
                op_rows.append(
                    f"    {{{script}, {kind}, {first + image}, 0x{palettes[palette]:08x}, "
                    f"0x{now:08x}, {{{hexs(words)}}}, {len(words)}}},"
                )
            now = (
                now
                + rng.choice(
                    [0, 1, 16, 16, 33, 400, 1200, 3749, 3751, 5000, 15001, 16000]
                )
            ) & 0xFFFFFFFF
        emu.heap_release(mark)
    lines.append("static const SpriteCacheImage kSpriteCacheImages[] = {")
    lines += [f"    {r}," for r in images_rows]
    lines.append("};")
    lines.append(
        f"static const std::uint32_t kSpriteCacheReleases[] = {{{', '.join(script_rows)}}};"
    )
    lines.append("static const SpriteCacheOp kSpriteCacheOps[] = {")
    lines += op_rows
    lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
