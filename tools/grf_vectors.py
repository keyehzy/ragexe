"""Test vectors for the GRF cipher and name hash, taken from the original in the emulation oracle.

usage: .venv/bin/python -I tools/grf_vectors.py > tests/unit/grf_cipher_vectors.inc

Inputs come from a small linear congruential generator that tests/unit/grf_test.cpp
repeats, so the file holds only the parameters and an FNV-1a hash of each output.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu import Emulator  # noqa: E402

# analysis/labels/inferred.functions.tsv
DES_CIPHER, SET_KEY = 0x4DC0C0, 0x4DC1A0
DECRYPT_BLOCKS_MIXED, DECRYPT_FIRST_BLOCKS = 0x4DC820, 0x4DCC40
HASHED_FILE_NAME_SET = 0x4DF750


def lcg_bytes(seed, n):
    x, out = seed, bytearray()
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    emu = Emulator().init_crt()
    cipher = emu.scratch(size=0x80)
    emu.call(DES_CIPHER, this=cipher)
    key = emu.call(SET_KEY, emu.scratch(b"nprontk!"), this=cipher).eax
    out_n = emu.scratch(size=4)

    print("// Generated by tools/grf_vectors.py from the original in the emulation oracle.")
    print("// {seed, size, digits, fnv1a64 of the output}; digits 0 means DecryptFirstBlocks.")
    print("static const CipherVector kCipherVectors[] = {")
    cases = [(s, 4096, d) for s, d in enumerate([1, 2, 3, 4, 5, 6, 7, 8], start=1)]
    cases += [(20, 8, 1), (21, 160, 5), (22, 168, 5), (23, 4096, 0), (24, 104, 0), (25, 8, 0)]
    for seed, size, digits in cases:
        data = lcg_bytes(seed, size)
        src, dst = emu.scratch(data), emu.scratch(size=size + 8)
        if digits:
            emu.call(DECRYPT_BLOCKS_MIXED, src, size, dst, out_n, key, digits, this=cipher)
        else:
            emu.call(DECRYPT_FIRST_BLOCKS, src, size, dst, out_n, key, this=cipher)
        assert emu.read_u32(out_n) == size
        print(f"    {{{seed}, {size}, {digits}, 0x{fnv1a64(emu.mem_read(dst, size)):016x}ull}},")
    print("};")

    print("// {name bytes, hash HashedFileName::Set computes}")
    print("static const NameVector kNameVectors[] = {")
    names = [b"", b"a", b"data\\Prontera.GAT", b"DATA\\TEXTURE\\\xc0\xaf\xc0\xfa.bmp", b"\xff\x80\x7f"]
    for name in names:
        obj = emu.scratch(size=0x110)
        emu.call(HASHED_FILE_NAME_SET, emu.scratch(name + b"\0"), this=obj)
        text = "".join(f"\\x{b:02x}" for b in name)
        print(f'    {{"{text}", 0x{emu.read_u32(obj):08x}u}},')
    print("};")


if __name__ == "__main__":
    main()
