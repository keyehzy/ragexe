std::string PlayerBodyName(std::int32_t job, std::int32_t sex) {
  return std::string(kRace) + kBody + At(kSexFolders, sex) + "\\" + At(kJobs, job) +
         At(kSexSuffixes, sex);
}

std::string PlayerHeadName(std::int32_t hair, std::int32_t sex) {
  if (hair < 0 || hair > kMaxHair) hair = kDefaultHair;
  return std::string(kRace) + kHead + At(kSexFolders, sex) + "\\" + HeadOf(hair, sex) +
         At(kSexSuffixes, sex);
}

std::string PlayerImfName(std::int32_t job, std::int32_t sex) {
  return std::string(At(kImfJobs, job)) + At(kSexSuffixes, sex) + ".imf";
}

PlayerSpriteNames PlayerHeadgearNames(std::int32_t sex, std::int32_t headgear) {
  if (headgear == 0) return {};
  const std::string name = std::string(kHeadgearFolder) + At(kSexFolders, sex) + "\\" +
                           At(kSexFolders, sex) + At(kHeadgear, headgear);
  if ((headgear == 0x12 || headgear == 0x13) && sex == 1) return {"", name};
  return {name, name};
}

bool CanShowWeapon(std::int32_t job, std::int32_t kind) {
  switch (job) {
    case 0: return kind == 1 || kind == 2 || kind == 6 || kind == 8 || kind == 10;
    case 1:
    case 7:
    case 0xd: return kind >= 1 && kind <= 9;
    case 2:
    case 9: return kind == 1 || kind == 10;
    case 3:
    case 0xb: return kind == 1 || kind == 0xb;
    case 4: return kind == 8 || kind == 10;
    case 5:
    case 10: return kind == 1 || kind == 2 || kind == 6 || kind == 7 || kind == 8;
    case 6:
    case 0x11: return (kind >= 1 && kind <= 2) || kind == 0xb;
    case 8: return kind == 8 || kind == 10 || kind == 0xf;
    case 0xc: return kind == 1 || kind == 2 || kind == 6 || (kind >= 0x10 && kind <= 0x16);
    case 0xe:
    case 0x15: return kind >= 1 && kind <= 8;
    case 0xf: return kind == 8 || kind == 10 || kind == 0xc;
    case 0x10: return kind == 1 || kind == 2 || kind == 10 || kind == 0xf;
    case 0x12: return kind == 1 || kind == 2 || kind == 6 || kind == 7 || kind == 8 || kind == 10;
    case 0x13: return kind == 1 || kind == 0xb || kind == 0xd;
    case 0x14: return kind == 1 || kind == 0xb || kind == 0xe;
    default: return kind == 1;
  }
}

std::array<PlayerSpriteNames, 2> PlayerWeaponNames(std::int32_t job, std::int32_t sex,
                                                   std::int32_t kind) {
  if (!CanShowWeapon(job, kind)) return {};
  const std::string name =
      std::string(kRace) + At(kJobFolders, job) + At(kSexSuffixes, sex) + At(kWeapons, kind);
  std::array<PlayerSpriteNames, 2> out{PlayerSpriteNames{name, name}, PlayerSpriteNames{}};
  if (ShowsGlow(kind)) out[1] = {name + kGlow, name + kGlow};
  return out;
}

std::int32_t ShieldKindOf(std::int32_t id) {
  switch (id) {
    case 0x835:
    case 0x836: return 1;
    case 0x837:
    case 0x838: return 2;
    case 0x839:
    case 0x83a: return 3;
    case 0x83b:
    case 0x83c:
    case 0x83e:
    case 0x83f: return 4;
    default: return 0;
  }
}

bool CanShowShield(std::int32_t job, std::int32_t kind) {
  if (kind > kHighIds) kind = ShieldKindOf(kind);
  switch (job) {
    case 0:
    case 2:
    case 3:
    case 9:
    case 0xb:
    case 0x10:
    case 0x13:
    case 0x14: return kind == 1;
    case 1:
    case 7:
    case 0xe: return kind > 0 && kind < 5;
    case 4:
    case 5:
    case 8:
    case 10:
    case 6:
    case 0xc:
    case 0x11: return kind > 0 && kind < 3;
    default: return false;
  }
}

PlayerSpriteNames PlayerShieldNames(std::int32_t job, std::int32_t sex, std::int32_t shield) {
  if (shield > kHighIds) shield = ShieldKindOf(shield);
  if (shield == 0 || !CanShowShield(job, shield)) return {};
  const std::string name = std::string(kShieldFolder) + At(kJobFolders, job) +
                           At(kSexSuffixes, sex) + At(kShields, shield);
  return {name, name};
}

std::string PlayerHeadPaletteName(std::int32_t hair, std::int32_t job, std::int32_t sex,
                                  std::int32_t palette) {
  if (palette == 0) return {};
  if (hair == 0) hair = job >= 1 && job <= 6 ? job + 1 : 1;
  return std::string(kHeadPalette) + HeadOf(hair, sex) + At(kSexSuffixes, sex) + "_" +
         std::to_string(palette) + ".pal";
}

std::string PlayerBodyPaletteName(std::int32_t job, std::int32_t sex, std::int32_t palette) {
  if (palette == 0) return {};
  return std::string(kBodyPalette) + At(kBodyPalettes, job) + At(kSexSuffixes, sex) + "_" +
         std::to_string(palette) + ".pal";
}

