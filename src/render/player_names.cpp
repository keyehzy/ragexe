template <std::size_t N>
const char* At(const std::array<const char*, N>& table, std::int32_t i) {
  return i >= 0 && static_cast<std::size_t>(i) < N ? table[static_cast<std::size_t>(i)] : "";
}

// The head sprite a hair style names for the sex: the male table for sex 1, else the
// female one.
const char* HeadOf(std::int32_t hair, std::int32_t sex) {
  return sex == 1 ? At(kMaleHair, hair) : At(kFemaleHair, hair);
}

bool ShowsGlow(std::int32_t kind) {
  return (kind >= 1 && kind <= 7) || (kind >= 0x10 && kind <= 0x16);
}

