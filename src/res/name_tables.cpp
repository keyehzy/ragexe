std::string_view JobName(std::int32_t job, std::int32_t service) {
  if (job < 0 || job >= kJobCount) return {};
  if (job == kMagician && service == 1) return "Mage";
  for (const JobNameEntry& entry : kJobNames)
    if (entry.job == job) return entry.name;
  return kUnnamedJob;
}

std::string_view SkillName(std::int32_t skill) {
  if (skill < 0 || static_cast<std::size_t>(skill) >= kSkillNames.size()) return {};
  return kSkillNames[static_cast<std::size_t>(skill)];
}

std::string_view GuildSkillName(std::int32_t index) {
  if (index < 0 || static_cast<std::size_t>(index) >= kGuildSkillNames.size()) return {};
  return kGuildSkillNames[static_cast<std::size_t>(index)];
}

std::string_view SexLetter(std::int32_t sex) {
  if (sex == 0) return "F";
  if (sex == 1) return "M";
  return {};
}

float JobShadowScale(std::int32_t job) {
  for (const ShadowEntry& entry : kShadowScales)
    if (entry.job == job) return entry.scale;
  return 1.0f;
}

